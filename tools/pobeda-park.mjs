// Сквер перед кинотеатром «Победа» (Большая Морская, 13): контур, аллея и
// скамейки для data/squares.json. Своего контура у сквера в OSM нет, дорожек
// внутри тоже — всё собрано из того, что в данных есть:
//   - рамка фасада модели models/kino_pobeda (ребро контура OSM w90822039
//     (-287.9,942.8)–(-283.2,961.0), начало (-285.55,951.9)): подиум u ±17.5,
//     боковые марши до d=2, центральный марш u ±4 (щёки ±4.9) до d≈9;
//   - тротуар Большой Морской — дорожка OSM w439397714 (ширина 2.5);
//   - стены соседей: кенасса w90821892 (её портик смотрит на юг, во двор
//     кинотеатра — refs/center-models.json), магазин w114116845, верх
//     Таврической лестницы w27737720 / w478729445.
// Аллея — продолжение центрального марша до тротуара: по NOTES.md модели марш
// «на деле длиннее и выходит к уличному тротуару», ширина — между щёками.
//
//   node tools/pobeda-park.mjs          — пересчитать и записать в squares.json
//   node tools/pobeda-park.mjs --dry    — только напечатать
import fs from 'node:fs';

const ID = 'sq-pobeda';
const R1 = v => Math.round(v * 10) / 10;

// рамка фасада: u — вдоль фасада на ЮЮВ, d — наружу на ЗСЗ, к улице
const A = [-287.9, 942.8], B = [-283.2, 961.0], O = [-285.55, 951.9];
const L = Math.hypot(B[0] - A[0], B[1] - A[1]);
const U = [(B[0] - A[0]) / L, (B[1] - A[1]) / L];
const N = [-U[1], U[0]][0] < 0 ? [-U[1], U[0]] : [U[1], -U[0]];
const F = (u, d) => [O[0] + U[0] * u + N[0] * d, O[1] + U[1] * u + N[1] * d];

// тротуар OSM w439397714 на этом участке: прямая, по ней — d кромки
const S0 = [-320.7, 915.5], S1 = [-298.0, 1005.5];
// d от фасада до осевой тротуара вдоль луча из точки фасада (u, 0)
const dWalk = u => {
  const [px, pz] = F(u, 0);
  const dx = S1[0] - S0[0], dz = S1[1] - S0[1];
  return ((S0[0] - px) * dz - (S0[1] - pz) * dx) / (N[0] * dz - N[1] * dx);
};
const WALK = 2.5 / 2 + 0.3;         // от осевой тротуара: полширины и бордюрный зазор

// Контур по часовой, обход от северо-запада. Граница с тротуаром — по его
// кромке; север — в 5 м от южной стены кенассы (перед её портиком площадка
// остаётся как есть); юг — вдоль верхней площадки Таврической лестницы.
const poly = [];
const P = (x, z) => poly.push(R1(x), R1(z));
// северная кромка: от тротуара вдоль кенассы, южная стена (-315.6,910.6)–(-301.7,907.9)
{
  const kx = [-315.6, 910.6], ky = [-301.7, 907.9];
  const kL = Math.hypot(ky[0] - kx[0], ky[1] - kx[1]);
  const nx = -(ky[1] - kx[1]) / kL, nz = (ky[0] - kx[0]) / kL;   // на юг
  const off = 5.0;
  // западный конец — на кромке тротуара
  const a = [kx[0] + nx * off, kx[1] + nz * off], b = [ky[0] + nx * off + 1.5, ky[1] + nz * off];
  // точка тротуарной кромки на той же широте
  const t = (a[1] - S0[1]) / (S1[1] - S0[1]);
  const wx = S0[0] + (S1[0] - S0[0]) * t + WALK / Math.cos(Math.atan2(S1[0] - S0[0], S1[1] - S0[1]));
  P(wx, a[1]);
  P(b[0], b[1]);
}
// к северо-западному углу крыла кинотеатра и вдоль крыла (d = -5.9 + 1.2)
for (const [u, d] of [[-28.6, -4.7], [-18.7, -4.7],
  // перед подиумом, отступ 0.8 м; у боковых маршей (|u| 4…10.7, до d=2) — 2.8
  [-18.3, 0.8], [-11.5, 0.8], [-11.5, 2.8],
  // щёки центрального марша ±4.9 до d=9.3: лестницу не засаживаем
  [-5.6, 2.8], [-5.6, 9.3], [5.6, 9.3], [5.6, 2.8],
  [11.5, 2.8], [11.5, 0.8], [18.3, 0.8], [18.7, -4.7], [28.6, -4.7]]) P(...F(u, d));
// южное крыло кончается у магазина w114116845: его западная стена
// (-268.9,981.4)–(-264.9,998.2), отступ 1.5 м на запад
P(-270.6, 981.2);
P(-266.6, 998.5);
// верхняя площадка Таврической лестницы: ступени w27737720 от (-283.3,1010.1),
// площадка до тротуара w478729445 — на 4.5 м севернее
P(-283.0, 1005.3);
P(-296.5, 1007.0);
// по кромке тротуара обратно на север
{
  const ex = WALK / Math.cos(Math.atan2(S1[0] - S0[0], S1[1] - S0[1]));
  // кромка тротуара: несколько точек, чтобы контур шёл по ней
  for (const z of [1004.0, 960, 930]) {
    const tt = (z - S0[1]) / (S1[1] - S0[1]);
    P(S0[0] + (S1[0] - S0[0]) * tt + ex, z);
  }
}

// Аллея: от подножия центрального марша (d = 8.8) до осевой тротуара.
const d0 = 8.9, d1 = dWalk(0);
const alley = { id: ID + '-alley', c: 4, w: 8, sf: 1, pts: [...F(0, d0), ...F(0, d1)].map(R1) };

// Скамейки — по две с каждой стороны аллеи, лицом к ней; урна у каждой пары.
// Сколько их на самом деле и где — данных нет: расстановка наугад.
const benches = [];
for (const s of [-1, 1])
  for (const d of [12.8, 18.6]) {
    const [x, z] = F(s * 6.7, d);
    benches.push({ k: 'bench', x: R1(x), z: R1(z) });
  }
for (const s of [-1, 1]) {
  const [x, z] = F(s * 6.7, 15.7);
  benches.push({ k: 'bin', x: R1(x), z: R1(z) });
}

const entry = {
  id: ID,
  name: 'Сквер перед кинотеатром «Победа»',
  kind: 'park',
  // м² на дерево: у парка по умолчанию 130 — здесь реже, перед фасадом-памятником
  // и в пределах +5% треугольников (замер в записке)
  dens: 180,
  poly,
  paths: [alley],
  furniture: benches,
  source: 'своего контура и дорожек в OSM нет; собран tools/pobeda-park.mjs из рамки фасада модели '
    + 'models/kino_pobeda (ребро контура w90822039, подиум и марши — по build.py), кромки тротуара '
    + 'Большой Морской w439397714, стен кенассы w90821892 (отступ 5 м перед её южным портиком) и '
    + 'магазина w114116845, верха Таврической лестницы w27737720/w478729445. Аллея — продолжение '
    + 'центрального марша до тротуара (NOTES.md модели: марш выходит к тротуару), ширина между щёками. '
    + 'Скамейки и урны — наугад. Что сквер там есть — со слов владельца и заметки street '
    + '(street-bm.json noBeds: «площадка перед „Победой“ — свой сквер с кедром и живой изгородью»).',
  checked: '2026-10-06',
};

if (process.argv.includes('--dry')) {
  console.log(JSON.stringify(entry));
} else {
  const f = new URL('../data/squares.json', import.meta.url);
  const list = JSON.parse(fs.readFileSync(f, 'utf8')).filter(s => s.id !== ID);
  list.push(entry);
  // координаты — с одним знаком, как записан соседний сквер (-384.0, а не -384)
  const fix = function (k, v) { return Array.isArray(this) && typeof v === 'number' ? `§${v.toFixed(1)}§` : v; };
  fs.writeFileSync(f, JSON.stringify(list, fix, 1).replace(/"§(-?[\d.]+)§"/g, '$1') + '\n');
  console.log('squares.json:', list.length, 'скверов; аллея', alley.pts.join(','), 'длина', R1(d1 - d0), 'м');
}
