# Фигуры (патинированная бронза) и гранитный постамент-клин сняты по фото Викисклада
# (refs/): боковой силуэт даёт позы, вид спереди — расположение блоков. Общая высота 41 м
# (по штыку), размеры частей — по масштабу фото (см. NOTES.md).
# Локальная система: +X — направление руки матроса (на ССЗ), +Y — влево, Z — вверх,
# ноль высоты — земля у основания башни матроса.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
