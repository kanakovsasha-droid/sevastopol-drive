def sailor():
    ys = 1.8
    fg = Fig(16.5, face=(1, 0, 0), bulk=1.2, seg=8)
    J = person(B, fg, pel=(-0.5, ys, 13.8), neck=(-1.7, ys, 18.9), head=(-1.0, ys, 20.7),
               shL=(-1.5, ys + 2.0, 18.5), shR=(-2.3, ys - 1.9, 18.5),
               haL=(3.4, ys + 1.9, 20.0), haR=(-4.4, ys - 1.7, 22.9),
               hipL=(-0.2, ys + 1.0, 13.4), hipR=(-0.8, ys - 1.0, 13.4),
               anL=(3.2, ys + 1.6, 8.75), anR=(-3.0, ys - 1.6, 8.75),
               polesA=((0, 0, -1), (-1, -0.3, 0.2)), polesL=((1, 0.1, 0.5), (1, 0, 0.4)),
               toe=((6, ys + 1.6, 8), (1, ys - 1.6, 8)), head_kind='cap', torso_w=1.3, head_r=1.15, arm_r=1.3, leg_r=1.25, leg_scale=0.80, arm_scale=0.98)
    # расклешённые брюки
    for sg, an in ((1, (3.2, ys + 1.6, 8.75)), (-1, (-3.0, ys - 1.6, 8.75))):
        kn = J['kn%d' % sg]; an = Vector(an)
        mid = kn + (an - kn) * 0.45
        tube(B, [mid, an + Vector((0, 0, -0.1))], [0.9, 1.65], 10)
    # бушлат: расширяющаяся пола на бёдрах
    skirt(B, [(Vector((-0.5, ys, 14.4)), 2.35, 2.10, lambda t: 1 + 0.05 * math.sin(4 * t)),
              (Vector((-0.5, ys, 13.2)), 2.55, 2.30, lambda t: 1 + 0.10 * math.sin(5 * t + 0.6)),
              (Vector((-0.4, ys, 12.0)), 2.95, 2.60, lambda t: 1 + 0.16 * math.sin(5 * t + 1.1))], seg=14)
    # гюйс (воротник), развевающийся за спиной
    tube(B, [Vector((-2.2, ys, 19.1)), Vector((-4.8, ys, 18.2)), Vector((-7.4, ys, 16.6))],
         [(0.25, 1.7), (0.22, 2.1), (0.15, 1.5)], 6)
    # ленты бескозырки
    for sg in (-1, 1):
        tube(B, [Vector((-1.9, ys + sg * 0.3, 20.9)), Vector((-4.0, ys + sg * 0.7, 21.6)), Vector((-6.2, ys + sg * 1.2, 21.0))], [0.13, 0.12, 0.07], 5)
    # винтовка с примкнутым штыком, вертикально над поднятой рукой
    tx0, ty = -4.9, ys - 1.7
    pts = [Vector((tx0, ty, 19.6)), Vector((tx0 + 0.15, ty, 24.5)), Vector((tx0 + 0.3, ty, 31.0)), Vector((tx0 + 0.45, ty, 34.0)), Vector((tx0 + 0.6, ty, 36.0)), Vector((tx0 + 0.75, ty, 41.0))]
    tube(B, pts, [(0.50, 0.38), (0.42, 0.34), (0.30, 0.30), (0.24, 0.24), (0.20, 0.20), (0.03, 0.03)], 8)
    # ремень винтовки
    tube('metal', [Vector((tx0 + 0.25, ty - 0.35, 28.5)), Vector((tx0 - 0.5, ty - 0.6, 27.0)), Vector((tx0 - 0.4, ty - 0.2, 25.3)), Vector((tx0 + 0.2, ty + 0.3, 26.5))], [0.09] * 4, 5)

