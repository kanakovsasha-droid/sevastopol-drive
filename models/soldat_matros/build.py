X0, Z0 = -885.0, 155.0
origin(X0, Z0)
set_rot(world_rot(-0.42, -0.91))
COL['wall3'] = ((0.21, 0.30, 0.25), 0.55)      # бронза с зелёной патиной
COL['metal'] = ((0.10, 0.15, 0.12), 0.5)
COL['wall2'] = ((0.40, 0.17, 0.15), 0.45)      # красный полированный гранит
COL['stone'] = ((0.56, 0.53, 0.50), 0.9)
COL['roof'] = ((0.36, 0.33, 0.20), 0.95)

B = 'wall3'
F0 = FR()

# ================================================================== ПОСТАМЕНТ
def plinth():
    G = 'wall2'
    # башня матроса: две ступени, передняя грань с наклоном вперёд
    frustum(G, F0, (-7.0, 5.0, -2.2, 6.0), (-6.4, 6.4, -1.6, 5.5), -4.0, 4.6, cap=True, base=False)
    box('wall2', F0, -6.6, 6.8, -1.9, 5.8, 4.6, 4.9)                                   # уступ-полка
    frustum(G, F0, (-5.8, 7.8, -1.0, 4.6), (-5.2, 8.4, -0.5, 4.1), 4.9, 8.0, cap=True)  # верх башни, нависает вперёд
    box('wall2', F0, -5.4, 8.6, -0.7, 4.3, 8.0, 8.15)
    # блок солдата и пологий клин вниз
    frustum(G, F0, (-17.0, -0.5, -8.2, 1.6), (-15.6, -1.4, -6.6, 0.4), -4.0, 3.5, cap=True)
    box('wall2', F0, -15.9, -1.2, -6.9, 0.7, 3.5, 3.7)
    # клин: сверху наклонная плоскость, плавно уходящая в землю на юго-востоке
    xs = [-15.6, -26.0, -36.0, -48.0]
    zs = [3.5, 2.4, 1.3, 0.3]
    hw = [4.2, 5.5, 7.5, 10.0]
    cy = -3.0
    for i in range(3):
        a0, a1 = xs[i], xs[i + 1]
        quad = [F0.p(a0, cy - hw[i], zs[i]), F0.p(a0, cy + hw[i], zs[i]), F0.p(a1, cy + hw[i + 1], zs[i + 1]), F0.p(a1, cy - hw[i + 1], zs[i + 1])]
        face(G, quad, UP)
        for s in (-1, 1):
            q = [F0.p(a0, cy + s * hw[i], zs[i]), F0.p(a1, cy + s * hw[i + 1], zs[i + 1]),
                 F0.p(a1, cy + s * hw[i + 1], -3.0), F0.p(a0, cy + s * hw[i], -3.0)]
            face(G, q, F0.N() * s)
    q = [F0.p(xs[-1], cy - hw[-1], zs[-1]), F0.p(xs[-1], cy + hw[-1], zs[-1]), F0.p(xs[-1], cy + hw[-1], -3.0), F0.p(xs[-1], cy - hw[-1], -3.0)]
    face(G, q, -F0.U())
    # швы-полосы на клине и на башне (полосы облицовки)
    for i in range(1, 3):
        x = xs[i]
        box('stone', F0, x - 0.12, x + 0.12, cy - hw[i], cy + hw[i], zs[i] - 0.05, zs[i] + 0.04)
    # плиты с надписями на боку башни и клина
    plate('metal', F0, -2.5, 1.5, -2.25, 1.0, 3.0, lines=5, seed=2, mat='metal') if False else None
    Fr = FR(0, 0, 0)
    plate(Fr, F0, 0, 0, 0, 0, 0) if False else None

