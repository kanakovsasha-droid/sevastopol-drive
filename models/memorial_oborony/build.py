# Мемориал героической обороны Севастополя 1941–1942 гг. (1967, арх. И. Е. Фиалко, скульптор В. В. Яковлев).
#
#   blender -b --python models/memorial_oborony/build.py -- [glb]
#
# Гранитная подпорная стена 32,4 м на площади Нахимова: внизу ниша с бронзово-гранитными плитами
# (воинские части и Герои), сверху глухая кладка с датами «1941 1942», в правой части — горельеф
# бойца с автоматом и тремя штыками, у подножия широкая лестница и Вечный огонь на ступенчатом
# постаменте. Ноль высоты — плита площади у подножия лестницы; терраса перед стеной на +0,85.
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'mon_common'))
from mon import *

A, Bp = (-89.1, 35.4), (-71.4, 62.5)            # ребро OSM way 724556805 (лицом на СВ)
INSIDE = (-100.0, 70.0)                          # точка за стеной (холм Матросского бульвара)
MID = ((A[0] + Bp[0]) / 2, (A[1] + Bp[1]) / 2)
# начало модели — середина подножия лестницы (6,4 м от стены наружу)
ln = math.hypot(Bp[0] - A[0], Bp[1] - A[1])
ux, uz = (Bp[0] - A[0]) / ln, (Bp[1] - A[1]) / ln
nx, nz = uz, -ux                                  # нормаль в сторону СВ
if nx * (INSIDE[0] - MID[0]) + nz * (INSIDE[1] - MID[1]) > 0:
    nx, nz = -nx, -nz
X0, Z0 = MID[0] + nx * 6.4, MID[1] + nz * 6.4
origin(X0, Z0)
F, L = frame_from(A, Bp, INSIDE)                  # u вдоль A→B, n наружу; F.o — точка A
F = Frame(F.o + F.n * (-0.0), F.u, F.n)

COL['stone'] = ((0.56, 0.55, 0.52), 0.9)          # ступени, цоколь
COL['wall'] = ((0.52, 0.51, 0.49), 0.95)          # серый гранит кладки
COL['wall2'] = ((0.23, 0.15, 0.13), 0.55)         # тёмно-бордовые плиты, постамент огня
COL['wall3'] = ((0.60, 0.59, 0.56), 0.9)          # горельеф — светлее кладки
COL['trim'] = ((0.66, 0.52, 0.22), 0.4)           # золото надписей и рамок
COL['metal'] = ((0.16, 0.15, 0.13), 0.5)
COL['roof'] = ((0.98, 0.52, 0.08), 0.4)           # пламя
COL['glass'] = ((0.10, 0.14, 0.17), 0.1)

T = 0.85                    # высота террасы над площадью
GR = -3.0
D_PLATE = -0.75             # плиты утоплены под нависающую часть стены
Z_PL0, Z_PL1 = T + 0.55, 3.6
Z_TOP = 8.3
UB = 6.4                    # начало стен: ступени идут от d = 4.2 до 6.4 (d от стены)

def build_terrace_steps():
    box('stone', F, -2.0, L + 2.0, -3.0, 4.2, GR, T)
    n = 4
    rise = T / n
    for i in range(n - 1):      # три ступени и площадь внизу
        top = T - rise * (i + 1)
        box('stone', F, -2.0, L + 2.0, 4.2 + 0.55 * i, 4.2 + 0.55 * (i + 1) + 0.02, GR, top)

def build_wall():
    # цоколь под плитами
    box('wall2', F, 3.2, L - 3.2, -0.8, D_PLATE + 0.8 - 0.0, T, T + 0.55)
    box('wall', F, 3.2, L - 3.2, -3.0, 0.0, T, T + 0.55)
    # плиты: ряд тёмных плит с золотой строкой
    ux_ = 3.2
    k = 0
    while ux_ < L - 3.2 - 0.01:
        w = min(1.65, L - 3.2 - ux_)
        box('wall2', F, ux_ + 0.03, ux_ + w - 0.03, D_PLATE - 0.1, D_PLATE + 0.04, Z_PL0, Z_PL1)
        # золотые строки (имитация текста) — две-три выпуклых полоски на плиту
        for r in range(4):
            zz = Z_PL1 - 0.45 - r * 0.5
            box('trim', F, ux_ + 0.2, ux_ + w - 0.2, D_PLATE + 0.04, D_PLATE + 0.065, zz, zz + 0.06)
        ux_ += w
        k += 1
    # золотая надпись-шапка над плитами (рода войск)
    box('trim', F, 3.4, L - 3.4, D_PLATE + 0.04, D_PLATE + 0.07, Z_PL1 - 0.14, Z_PL1 - 0.06)
    # глухая стена сверху — кладка рядами блоков с чередующимся вылетом
    z = Z_PL1
    rows = 5
    hrow = (Z_TOP - Z_PL1) / rows
    for r in range(rows):
        off = 0.0 if r % 2 == 0 else 1.2
        u = 3.2 - 0.0
        # над нишей
        uu = 3.2
        edges = [uu]
        while uu < L - 3.2:
            uu = min(uu + 2.7 + 0.5 * ((r * 7 + int(uu)) % 3), L - 3.2)
            edges.append(uu)
        for a, b in zip(edges[:-1], edges[1:]):
            e = 0.04 if (int(a) + r) % 2 else 0.0
            box('wall', F, a + 0.015, b - 0.015, -3.0, e, z, z + hrow - 0.02, bottom=False)
        z += hrow
    # боковые пилоны: сплошные до земли
    for (u0, u1) in ((0.0, 3.2), (L - 3.2, L)):
        z = GR
        box('wall', F, u0, u1, -3.0, 0.0, GR, T)
        edges = [T, T + 1.3, T + 2.6, T + 3.9, T + 5.2, Z_TOP]
        for za, zb in zip(edges[:-1], edges[1:]):
            box('wall', F, u0 + 0.015, u1 - 0.015, -3.0, 0.03 if za > T + 2 else 0.0, za, zb - 0.02, bottom=False)
    box('wall', F, -0.0, L, -3.0, 0.1, Z_TOP, Z_TOP + 0.2)                          # венчающая плита
    # цоколь у пилонов
    for (u0, u1) in ((0.0, 3.2), (L - 3.2, L)):
        box('stone', F, u0 - 0.1, u1 + 0.1, -3.0, 0.25, T, T + 0.4)
    # даты «1941 1942» — крупные выпуклые цифры слева (в сторону большего u)
    seg7 = {'1': 'bc', '9': 'abcdfg', '4': 'bcfg', '2': 'abged'}
    def digit(ch, uc, zc, w=0.9, h=1.5, s=0.2):
        d0 = 0.0
        zz0, zz1, zzm = zc - h / 2, zc + h / 2, zc
        segs = {'a': (uc - w / 2, uc + w / 2, zz1 - s, zz1), 'g': (uc - w / 2, uc + w / 2, zzm - s / 2, zzm + s / 2),
                'd': (uc - w / 2, uc + w / 2, zz0, zz0 + s),
                'f': (uc + w / 2 - s, uc + w / 2, zzm, zz1), 'b': (uc - w / 2, uc - w / 2 + s, zzm, zz1),
                'e': (uc + w / 2 - s, uc + w / 2, zz0, zzm), 'c': (uc - w / 2, uc - w / 2 + s, zz0, zzm)}
        for sg in seg7[ch]:
            a, b, c, d = segs[sg]
            box('wall3', F, a, b, d0, d0 + 0.12, c, d)
    u = L - 4.0
    for ch in '1941':
        digit(ch, u, 6.2); u -= 1.4
    u -= 0.7
    for ch in '1942':
        digit(ch, u, 6.2); u -= 1.4

def px(x, y):
    return ((1230 - x) / 58.0, Z_PL1 + (600 - y) / 58.0)

def poly(pts):
    return [px(x, y) for x, y in pts]

def build_relief():
    # фон выступающего блока
    prism_uz('wall3', F, poly([(410, 335), (435, 205), (735, 215), (735, 262), (1175, 268), (1180, 365), (1050, 405),
                              (1040, 440), (870, 600), (440, 590)]), 0.0, 0.7)
    # косая плита-«нога» снизу вправо
    prism_uz('wall3', F, poly([(435, 548), (560, 420), (1030, 440), (1030, 475), (875, 600), (440, 590)]), 0.7, 1.15)
    # верхний левый блок с кулаком
    prism_uz('wall3', F, poly([(440, 335), (480, 238), (560, 232), (560, 330)]), 0.7, 1.2)
    # торс бойца
    prism_uz('wall3', F, poly([(618, 296), (735, 262), (795, 335), (765, 445), (700, 495), (585, 430)]), 1.15, 1.75)
    # голова и кулак с зажатым блоком
    u, z = px(748, 300)
    ellipsoid('wall3', F.p(u, 1.85, z), 0.46, 0.4, 0.55, 10, 5)
    u, z = px(595, 245)
    ellipsoid('wall3', F.p(u, 1.5, z), 0.4, 0.35, 0.4, 8, 4)
    prism_uz('wall3', F, poly([(640, 270), (720, 262), (722, 320), (640, 330)]), 1.15, 1.65)
    # рука с автоматом — длинная горизонтальная балка вправо (в сторону меньшего u)
    prism_uz('wall3', F, poly([(790, 328), (1040, 320), (1040, 372), (790, 378)]), 1.3, 1.85)
    # три штыка и верхняя плита (клинки), выходят вперёд
    for (y0, y1, ytip) in ((300, 326, 285), (342, 370, 350), (388, 418, 425)):
        prism_uz('wall3', F, poly([(1010, y0), (1180, ytip), (1180, ytip + 18), (1010, y1)]), 1.0, 1.5)
    prism_uz('wall3', F, poly([(865, 262), (1175, 268), (1175, 322), (865, 296)]), 0.7, 1.3)
    # ноги бойца и поднятая рука с кулаком
    prism_uz('wall3', F, poly([(585, 430), (700, 495), (735, 590), (640, 590), (600, 520)]), 1.1, 1.55)
    u0, z0 = px(640, 330); u1, z1 = px(595, 255)
    limb('wall3_s', F.p(u0, 1.6, z0), F.p(u1, 1.6, z1), 0.28, 0.24, 8)
    u0, z0 = px(780, 340); u1, z1 = px(1000, 345)
    limb('wall3_s', F.p(u0, 1.9, z0), F.p(u1, 1.9, z1), 0.24, 0.2, 8)
    # горизонтальные перья-блоки слева вверху
    prism_uz('wall3', F, poly([(435, 205), (735, 215), (735, 255), (435, 245)]), 0.7, 1.0)

def build_flame():
    uc, dc = 15.5, 3.5
    for k, (h, r) in enumerate(((0.2, 1.05), (0.4, 0.8), (0.6, 0.55))):
        box('wall2', F, uc - r, uc + r, dc - r, dc + r, T + (h - 0.2), T + h)
    # чаша: тело вращения вокруг вертикальной оси через (uc, dc)
    p = F.p(uc, dc, 0)
    lathe('metal_s', Vector((p.x, p.y, 0)), [(0.18, T + 0.6), (0.4, T + 0.66), (0.46, T + 0.8), (0.34, T + 0.88), (0.0, T + 0.9)], 16, cap=False)
    # пламя — конус
    lathe('roof', Vector((p.x, p.y, 0)), [(0.30, T + 0.9), (0.24, T + 1.15), (0.12, T + 1.45), (0.0, T + 1.65)], 8, cap=False)
    # венки у стены (цветочные клумбы) — две красные полосы
    for u0, u1 in ((3.5, 13.5), (17.5, 28.5)):
        box('stone', F, u0, u1, 1.2, 1.55, T, T + 0.3)

def build_kiosks():
    # стеклянные посты у торцов с золотыми каркасами
    for uc in (1.6, L - 1.6):
        for k in (-0.6, 0.6):
            u = uc + k * 1.2
            box('trim', F, u - 0.55, u - 0.5, 1.2, 1.3, T, T + 2.2)
            box('trim', F, u + 0.5, u + 0.55, 1.2, 1.3, T, T + 2.2)
            box('trim', F, u - 0.55, u + 0.55, 1.2, 1.3, T + 2.15, T + 2.25)
            box('glass', F, u - 0.5, u + 0.5, 1.22, 1.26, T + 0.05, T + 2.15)

def build():
    build_terrace_steps()
    build_wall()
    build_relief()
    build_flame()
    build_kiosks()

build()
finish('memorial_oborony', __file__, 25000)
