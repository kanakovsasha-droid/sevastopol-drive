# Памятник В. И. Ленину на Центральном холме (площадь Ленина), Севастополь.
#
#   blender -b --python models/lenin/build.py -- [glb]
#
# Бронзовая фигура Ленина (указывает вперёд правой рукой, в левой — свёрнутые бумаги) на высоком
# сужающемся гранитном постаменте с пирамидальным скатом; на угловых тумбах — четыре коленопреклонённые
# фигуры (рабочий, красноармеец, краснофлотец, крестьянка). Спереди (на север) — лестница.
# Размеры сняты по масштабу фото Викисклада (refs/): всего ~18,8 м, скульптура ~5,8 м.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = -165.0, 569.0
origin(X0, Z0)
set_rot(world_rot(-0.17, -0.985))
COL['wall3'] = ((0.22, 0.27, 0.24), 0.55)      # бронза с патиной
COL['metal'] = ((0.12, 0.14, 0.13), 0.5)
COL['wall2'] = ((0.28, 0.30, 0.30), 0.5)       # тёмно-серый гранит/лабрадорит
COL['stone'] = ((0.55, 0.54, 0.52), 0.9)
B = 'wall3'; G = 'wall2'
F0 = FR()

# ------------------------------------------------------------------ постамент
frustum(G, F0, (-8.8, 8.8, -8.8, 8.8), (-8.0, 8.0, -8.0, 8.0), -0.5, 1.5)
box('stone', F0, -8.1, 8.1, -8.1, 8.1, 1.45, 1.55)
frustum(G, F0, (-3.9, 3.9, -3.9, 3.9), (-3.5, 3.5, -3.5, 3.5), 1.5, 3.1)
box(G, F0, -3.6, 3.6, -3.6, 3.6, 3.1, 3.3)
frustum(G, F0, (-3.3, 3.3, -3.3, 3.3), (-1.9, 1.9, -1.9, 1.9), 3.3, 5.0)       # пирамидальный скат
box(G, F0, -2.0, 2.0, -2.0, 2.0, 5.0, 5.2)
frustum(G, F0, (-1.75, 1.75, -1.75, 1.75), (-1.7, 1.7, -1.7, 1.7), 5.2, 7.4)
box(G, F0, -1.85, 1.85, -1.85, 1.85, 7.4, 7.6)
frustum(G, F0, (-1.65, 1.65, -1.65, 1.65), (-1.2, 1.2, -1.2, 1.2), 7.6, 12.7)  # сужающийся ствол
box(G, F0, -1.45, 1.45, -1.45, 1.45, 12.7, 13.0)
# надпись и звезда на лицевой грани ствола
plate('metal', FR(0, 0, -90), -0.8, 0.8, 1.62, 5.6, 6.8, lines=3, seed=7)
# угловые тумбы
for sx in (-1, 1):
    for sy in (-1, 1):
        cx, cy = sx * 5.3, sy * 5.3
        box(G, F0, cx - 1.5, cx + 1.5, cy - 1.5, cy + 1.5, 1.5, 3.7)
        box(G, F0, cx - 1.6, cx + 1.6, cy - 1.6, cy + 1.6, 3.55, 3.75)
# лестница к площадке (на север = вперёд, +X)
Fs = FR(0, 0, -90)
steps('stone', Fs, -9.5, 9.5, 8.6, 0.0, 6, 0.3, 0.55)
box('stone', Fs, -9.8, 9.8, 8.0, 8.6, -0.2, 0.0)

# ------------------------------------------------------------------ Ленин
zT = 13.0
fg = Fig(5.9, face=(1, 0, 0), bulk=1.15, seg=8)
person(B, fg, pel=(-0.05, 0, zT + 2.85), neck=(0.05, 0, zT + 4.85), head=(0.15, 0, zT + 5.35),
       shL=(0.0, 0.62, zT + 4.6), shR=(0.0, -0.62, zT + 4.6),
       haL=(0.25, 0.85, zT + 2.7), haR=(1.55, -1.55, zT + 5.65),
       hipL=(0.0, 0.22, zT + 2.7), hipR=(0.0, -0.22, zT + 2.7),
       anL=(0.15, 0.30, zT + 0.28), anR=(-0.25, -0.30, zT + 0.28),
       polesA=((0, 0.2, -1), (0, -0.3, -0.2)), polesL=((1, 0, 0.1), (1, 0, 0.1)),
       toe=((2, 0.3, zT), (2, -0.3, zT)), head_kind='bald', torso_w=1.4, head_r=1.25, arm_r=1.25, leg_r=1.15, leg_scale=0.97)
# пиджак: расходящиеся полы ниже пояса, правая пола отлетает
skirt(B, [(Vector((0.0, 0, zT + 3.45)), 0.46, 0.36, None),
          (Vector((0.0, 0, zT + 2.9)), 0.52, 0.50, lambda t: 1 + 0.06 * math.sin(5 * t)),
          (Vector((-0.05, -0.05, zT + 2.25)), 0.58, 0.62, lambda t: 1 + 0.10 * math.sin(4 * t + 1))], seg=12)
# бородка и воротник
blob(B, Vector((0.32, 0, zT + 5.18)), 0.1, 0.12, 0.14, seg=8, rings=3)
# свёрнутые бумаги в левой руке
tube(B, [Vector((0.18, 0.88, zT + 2.55)), Vector((0.62, 0.88, zT + 2.50))], [0.11, 0.11], 8)

# ------------------------------------------------------------------ четыре коленопреклонённые фигуры
def kneel(cx, cy, zb, ang, kind):
    a = math.radians(ang); ca, sa = math.cos(a), math.sin(a)
    T = lambda x, y, z: Vector((cx + x * ca - y * sa, cy + x * sa + y * ca, zb + z))
    fgk = Fig(3.0, face=(ca, sa, 0), bulk=1.1, seg=8)
    hk = {'worker': 'hair', 'soldier': 'helmet', 'sailor': 'cap', 'peasant': 'hair'}[kind]
    person(B, fgk, pel=T(0, 0, 1.0), neck=T(0.2, 0, 2.0), head=T(0.28, 0, 2.3),
           shL=T(0.15, 0.42, 1.9), shR=T(0.15, -0.42, 1.9),
           haL=T(0.7, 0.35, 1.1), haR=T(0.2, -0.5, 1.0),
           hipL=T(0, 0.18, 0.95), hipR=T(0, -0.18, 0.95),
           anL=T(0.8, 0.2, 0.2), anR=T(-0.7, -0.2, 0.2),
           polesA=(T(0, 0, -1) - T(0, 0, 0), T(0, -0.3, -1) - T(0, 0, 0)),
           polesL=(T(1, 0, 1) - T(0, 0, 0), T(1, 0, -1) - T(0, 0, 0)),
           toe=(T(2, 0.2, 0.2), T(-2, -0.2, 0.2)),
           head_kind=hk, torso_w=1.25, head_r=1.05, arm_r=1.1, leg_r=1.1)
    if kind == 'peasant':
        skirt(B, [(T(0, 0, 1.15), 0.42, 0.42, None), (T(0, 0, 0.6), 0.6, 0.62, lambda t: 1 + 0.06 * math.sin(5 * t)),
                  (T(0, 0, 0.05), 0.7, 0.72, None)], seg=12)
    if kind == 'soldier':
        tube(B, [T(0.9, -0.3, 0.2), T(0.9, -0.3, 2.3), T(0.9, -0.3, 3.3)], [0.08, 0.08, 0.04], 6)
    if kind == 'worker':
        tube(B, [T(0.5, 0.7, 0.18), T(0.5, 0.7, 1.0)], [0.06, 0.06], 6)
kneel(5.3, 5.3, 3.7, 40, 'worker')
kneel(5.3, -5.3, 3.7, -40, 'sailor')
kneel(-5.3, 5.3, 3.7, 130, 'peasant')
kneel(-5.3, -5.3, 3.7, -130, 'soldier')

done('lenin', __file__, -165.0, 569.0, 'Памятник В. И. Ленину на Центральном холме')
