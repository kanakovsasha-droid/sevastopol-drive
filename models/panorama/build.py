def rad(d): return math.radians(d)

def dirv(a):
    """Единичный вектор от центра наружу; a — угол от запада к югу (рад)."""
    return Vector((-math.cos(a), -math.sin(a)))

def P3(r, a, z):
    v = C + dirv(a) * r
    return Vector((v.x, v.y, z))

def tf(a, r=R):
    """Касательная рамка на круге: u — вдоль (к югу при a=0), n — наружу."""
    d = dirv(a)
    return Frame(C + d * r, Vector((math.sin(a), -math.cos(a))), d)

def rev(m, pts, seg=60):
    """Тело вращения по ломаной (r, z); нормаль грани — (dz, -dr), то есть профиль обходят против часовой
    стрелки (r вправо, z вверх). Радиус — апофема: грань встаёт ровно на заданный r."""
    dA = 2 * math.pi / seg
    off = -dA / 2
    k = 1 / math.cos(dA / 2)
    for i in range(len(pts) - 1):
        (r0, z0), (r1, z1) = pts[i], pts[i + 1]
        n = (z1 - z0, -(r1 - r0))
        for s in range(seg):
            a, b = off + s * dA, off + (s + 1) * dA
            q = [P3(r0 * k, a, z0), P3(r0 * k, b, z0), P3(r1 * k, b, z1), P3(r1 * k, a, z1)]
            qq = []
            for p in q:
                if not any((p - x).length < 1e-6 for x in qq):
                    qq.append(p)
            if len(qq) < 3: continue
            dv = dirv((a + b) / 2)
            face(m, qq, Vector((dv.x * n[0], dv.y * n[0], n[1])))

def ring(m, r_in, r_out, z0, z1, seg=60, top=True, bottom=True):
    """Кольцевая полка (без внутренней грани)."""
    pts = []
    if bottom: pts += [(r_in, z0), (r_out, z0)]
    else: pts += [(r_out, z0)]
    pts += [(r_out, z1)]
    if top: pts += [(r_in, z1)]
    rev(m, pts, seg)

def ball(m, base, r=0.25):
    prof = [(0.01, 0.0), (0.45 * r, 0.04 * r), (0.85 * r, 0.3 * r), (r, 0.9 * r), (0.85 * r, 1.5 * r),
            (0.45 * r, 1.85 * r), (0.01, 2.0 * r)]
    lathe(m, base, prof, 8)

