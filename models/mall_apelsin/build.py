# ТРЦ «Апельсин», пр. Героев Сталинграда, 27 — модель с нуля.
#
#   blender -b --python models/mall_apelsin/build.py -- [glb]
#
# Длинный корпус в светлом гофрированном металле с лентой окон; западный
# торец — скруглённый барабан, перед ним одноэтажная стеклянная пристройка
# в оранжевых рамах под оранжевым поясом. Главный фасад — на юг, к стоянке у
# проспекта: на кровле оранжевое «Апельсин» с апельсином вместо «А» и
# подписью «ТОРГОВО-РАЗВЛЕКАТЕЛЬНЫЙ ЦЕНТР», у барабана вертикальный щит
# продуктового (был «ЕКО маркет», теперь «Яблоко 8-24»), по первому этажу
# оранжевая полоса DNS. Фото 2017–2024 (refs/malls/apelsin). Что откуда — NOTES.md.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mall_kit import *

POLY = [(-7021.4, 3561.3), (-7003.4, 3559.1), (-7004.0, 3554.9), (-6993.4, 3552.9), (-6994.1, 3550.0),
        (-6969.1, 3545.4), (-6969.8, 3541.5), (-6924.1, 3532.0), (-6918.9, 3558.2), (-6918.0, 3563.7),
        (-6919.0, 3568.8), (-6920.4, 3570.4), (-6922.6, 3572.7), (-6928.4, 3574.6), (-6928.9, 3571.7),
        (-6932.3, 3572.4), (-6997.2, 3585.3), (-6998.5, 3579.8), (-7001.7, 3580.6), (-7005.2, 3581.3),
        (-7012.2, 3580.3), (-7017.7, 3576.4), (-7020.4, 3572.7)]
ARC_W = [(-6998.5, 3579.8), (-7001.7, 3580.6), (-7005.2, 3581.3), (-7012.2, 3580.3), (-7017.7, 3576.4),
         (-7020.4, 3572.7), (-7021.4, 3561.3)]
INSIDE = (-6968.0, 3560.0)
P0, P1 = (-6997.2, 3585.3), (-6932.3, 3572.4)  # южный фасад
DC = fit_circle(ARC_W)
origin(*P0)
F, LEN = frame_lr(P0, P1, INSIDE)              # u: с запада на восток, вправо для зрителя на стоянке

COL['wall'] = ((0.80, 0.78, 0.72), 0.55)      # светлый гофролист
COL['wall2'] = ((0.66, 0.64, 0.60), 0.55)     # рёбра гофра
COL['roof'] = ((0.52, 0.51, 0.49), 0.85)
COL['glass'] = ((0.15, 0.20, 0.25), 0.12)
mat('orange', (0.95, 0.42, 0.07), 0.5)
mat('oframe', (0.95, 0.42, 0.07), 0.5)          # оранжевые рамы витрин
mat('logo', (0.95, 0.38, 0.06), 0.45)         # буквы «Апельсин»
mat('leaf', (0.25, 0.55, 0.12), 0.6)
mat('white', (0.97, 0.97, 0.97), 0.5)
mat('dark', (0.08, 0.10, 0.09), 0.5)
mat('green', (0.40, 0.72, 0.12), 0.45)
lod_keep('orange', 'logo')

GROUND = -3.0
H = 12.6

# ------------------------------------------------------------------ корпус
# барабан: прямую часть корпуса собираем без западной дуги, дугу — отдельно
BODY = [p for p in POLY if p not in ARC_W[1:-1]]
prism_world('wall', BODY, GROUND, H, roof='roof')
cx, cz, R = DC
a0, a1 = ang_of(DC[:2], ARC_W[0]), ang_of(DC[:2], ARC_W[-1])
if (a1 - a0) % 360 > 180: a0, a1 = a1, a0
if a1 < a0: a1 += 360
C = W(cx, cz)
n = 14
angs = [math.radians(a0 + (a1 - a0) * i / n) for i in range(n + 1)]
rim = [Vector((C.x + R * math.cos(a), C.y + R * math.sin(a))) for a in angs]
V = lambda p, z: Vector((p.x, p.y, z))
for i in range(n):
    a, b = rim[i], rim[i + 1]
    m = (a + b) / 2 - C
    face('wall', [V(a, GROUND), V(b, GROUND), V(b, H), V(a, H)], Vector((m.x, m.y, 0)))
face('roof', [V(p, H + 0.02) for p in rim], UP)          # кровля сегмента барабана
# гофр: рёбра по барабану и по фасаду
for i, a in enumerate(angs):
    for k in range(3):
        t = a + (angs[1] - angs[0]) * k / 3 if i < n else None
        if t is None: continue
        p = Vector((C.x + (R + 0.04) * math.cos(t), C.y + (R + 0.04) * math.sin(t)))
        beam('wall2', V(p, 5.4), V(p, H - 0.1), 0.09, 0.09)
for k in range(int(LEN / 0.9)):
    u = 0.5 + k * 0.9
    box('wall2', F, u - 0.04, u + 0.04, 0, 0.07, 5.3, H - 0.1, bottom=False)
# лента окон под кровлей — по барабану и по фасаду
drum(DC[:2], R + 0.12, a0, a1, 7.4, 9.7, n=n, rows=[8.55])
curtain(F, 0.5, LEN - 1.0, 8.2, 10.0, 0.12, du=1.8, dz=1.8)
box('wall2', F, 0, LEN, 0, 0.3, H - 0.3, H + 0.3)

# одноэтажная стеклянная пристройка перед барабаном: оранжевые рамы и пояс
RA = R + 3.0
drum(DC[:2], RA, a0 - 6, a1, 0.0, 4.0, n=12, frame='oframe', rows=[2.6], mw=0.14)
ring('orange', DC[:2], R - 0.2, RA + 0.15, a0 - 6, a1, 4.0, 5.3, n=12)
# первый этаж по фасаду: витрины в оранжевых рамах, оранжевая полоса DNS
curtain(F, 1.0, LEN - 1.0, 0.0, 3.9, 0.08, du=2.4, dz=3.9, frame='oframe', mw=0.12)
box('orange', F, 2.0, 36.0, 0, 0.45, 4.1, 5.2)
text('white', F, 'DNS', 6.0, 4.3, 0.75, 0.45, depth=0.06, width=4.6)
text('white', F, 'ЦИФРОВОЙ', 14.5, 4.38, 0.55, 0.45, depth=0.06, width=7.5)
text('white', F, 'www.dns-shop.ru', 28.0, 4.4, 0.5, 0.45, depth=0.06, width=10.0)

# щит продуктового у барабана: «Яблоко 8-24»
board(F, -1.5, 4.5, 5.8, 11.6, 0.6, 'dark', depth=0.3)
text('green', F, 'Яблоко', 1.5, 9.3, 1.2, 0.9, depth=0.08, fnt='Brush Script.ttf', width=5.2, res=1)
disc('orange', F, 3.9, 10.3, 0.4, 0.9, depth=0.06, seg=10)
text('green', F, '8-24', 1.5, 6.6, 1.6, 0.9, depth=0.08, width=4.6)

# ------------------------------------------------------------------ вывеска на кровле
LU = LEN * 0.68
truss(F, LU - 9.0, LU + 9.5, H + 0.3, H + 3.6, -1.5, bays=7)
disc('logo', F, LU - 7.6, H + 2.3, 1.35, -1.25, depth=0.3, seg=18)          # апельсин вместо «А»
disc('white', F, LU - 7.6, H + 2.3, 0.75, -0.94, depth=0.05, seg=14)
disc('leaf', F, LU - 8.6, H + 3.7, 0.45, -1.25, depth=0.12, seg=8)
text('logo', F, 'пельсин', LU + 1.4, H + 1.3, 2.0, -1.25, depth=0.3, width=14.0)
text('logo', F, 'ТОРГОВО-РАЗВЛЕКАТЕЛЬНЫЙ ЦЕНТР', LU + 0.5, H + 0.45, 0.55, -1.25, depth=0.12, width=17.5)

finish('mall_apelsin', __file__)
