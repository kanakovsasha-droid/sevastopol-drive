# Памятник адмиралу В. А. Корнилову на Малаховом кургане, Севастополь.
#
#   blender -b --python models/kornilov_malahov/build.py -- [glb]
#
# Корнилов (бронза) полулежит на вершине бронзовой скалы и указывает рукой вперёд («Отстаивайте же Севастополь»);
# у подножия скалы матрос с ядром у ствола орудия на габионе. Гранитный трёхъярусный постамент со ступенями,
# перед ним гранитная плита с крестом из ядер. Размеры по масштабу фото (r0, r2): всего ~9,6 м.
# Ноль высоты — площадка. Лицом на ЮВ (к входу на площадку).
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = 1796.7, 1443.4
origin(X0, Z0)
set_rot(world_rot(0.65, 0.76))
COL['wall3'] = ((0.17, 0.20, 0.17), 0.5)       # тёмная бронза
COL['metal'] = ((0.10, 0.11, 0.10), 0.5)
COL['wall2'] = ((0.30, 0.32, 0.31), 0.5)       # тёмный серо-зелёный гранит
COL['stone'] = ((0.62, 0.58, 0.52), 0.9)       # светлый камень плиты, площадка
B = 'wall3'; G = 'wall2'
F0 = FR()

# ------------------------------------------------------------------ постамент
box('stone', F0, -5.0, 9.5, -5.5, 5.5, -0.4, 0.02)
box(G, F0, -3.9, 4.4, -4.7, 4.7, -0.3, 0.45)
for s in (-1, 1):                                              # боковые крылья лестницы
    u0, u1 = sorted((s * 3.05, s * 4.45))
    frustum(G, F0, (-3.5, 3.5, u0, u1), (-3.4, 3.2, u0 + 0.05 * s, u1 - 0.05 * s), 0.45, 1.5)
Fs = FR(0, 0, -90)
steps(G, Fs, -3.0, 3.0, 3.4, 1.35, 3, 0.45, 0.5)
frustum(G, F0, (-2.9, 2.9, -3.4, 3.4), (-2.0, 2.0, -2.45, 2.45), 0.45, 3.6)          # главный постамент
box(G, F0, -2.1, 2.1, -2.55, 2.55, 3.4, 3.65)
# плита с крестом из ядер перед памятником
box('stone', F0, 5.1, 8.1, -1.9, 1.9, 0.0, 0.28)
for i in range(11):
    blob(B, Vector((5.9 + i * 0.22, 0, 0.30)), 0.17, 0.17, 0.17, seg=6, rings=3, bot=0.0)
for i in range(-3, 4):
    blob(B, Vector((7.5, i * 0.45, 0.30)), 0.17, 0.17, 0.17, seg=6, rings=3, bot=0.0)

# ------------------------------------------------------------------ скала
import random
rnd = random.Random(4)
zs = [3.6, 4.35, 5.15, 5.9, 6.55]
rx = [1.9, 1.7, 1.5, 1.35, 1.25]
ry = [2.3, 2.05, 1.8, 1.6, 1.45]
off = [0.0, -0.05, -0.1, -0.25, -0.3]
rocks = []
for i, z in enumerate(zs):
    ph = rnd.random() * 6
    rocks.append((Vector((off[i], 0.0, z)), rx[i], ry[i], (lambda p: (lambda t: 1 + 0.09 * math.sin(3 * t + p) + 0.05 * math.sin(7 * t + 2 * p)))(ph)))
skirt(B, rocks, seg=14, caps=(False, True))
for (x, y, z, r) in ((1.9, -1.3, 3.9, 0.55), (2.0, 0.2, 3.85, 0.6), (1.85, 1.4, 3.9, 0.5), (1.5, -2.1, 3.85, 0.5), (1.6, 2.0, 3.85, 0.55),
                     (1.7, -0.6, 4.35, 0.4), (1.65, 0.8, 4.3, 0.4), (0.5, 2.6, 3.9, 0.55)):
    blob(B, Vector((x, y, z)), r, r, r * 0.8, seg=6, rings=3)
# надпись «Отстаивайте же Севастополь» и посвящение на скале
Fr = FR(0, 0, -90)
plate('metal', Fr, -0.8, 0.8, 1.5, 4.2, 5.4, lines=5, seed=8, pr=0.03)
plate('metal', Fr, -0.9, 0.9, 1.35, 5.6, 5.95, lines=1, seed=2, pr=0.03)

# ------------------------------------------------------------------ Корнилов (сидит на вершине, указывает рукой влево от зрителя)
z0 = 6.5
fg = Fig(4.6, face=(0.4, -0.9, 0), bulk=1.1, seg=8)
person(B, fg, pel=(0.05, 0.1, z0 + 0.5), neck=(-0.05, 0.4, z0 + 2.15), head=(0.0, 0.3, z0 + 2.55),
       shL=(0.05, -0.30, z0 + 1.85), shR=(-0.15, 1.0, z0 + 1.80),
       haL=(1.1, -1.3, z0 + 1.75), haR=(-0.2, 1.4, z0 + 0.65),
       hipL=(0.1, -0.2, z0 + 0.45), hipR=(0.0, 0.4, z0 + 0.45),
       anL=(1.15, -2.0, z0 - 0.15), anR=(0.55, -1.2, z0 + 0.25),
       polesA=((0, 0, -1), (0, 0.3, -1)), polesL=((0.3, -0.3, 1), (0.5, -0.4, 1)),
       toe=((2, -2.5, z0 - 0.3), (1.5, -1.8, z0)), head_kind='bare', torso_w=1.2, head_r=1.0, arm_r=1.15, leg_r=1.1)
# полы сюртука, ниспадающие на скалу
skirt(B, [(Vector((0.0, 0.5, z0 + 0.7)), 0.55, 0.75, None), (Vector((-0.15, 0.9, z0 + 0.25)), 0.7, 0.9, lambda t: 1 + 0.1 * math.sin(4 * t)),
          (Vector((-0.3, 1.2, z0 - 0.15)), 0.8, 1.0, None)], seg=10)

# ------------------------------------------------------------------ матрос у орудия
cx, cy, zb = -0.2, 3.3, 3.55
fgs = Fig(3.2, face=(0.4, -0.9, 0), bulk=1.1, seg=8)
person(B, fgs, pel=(cx, cy, zb + 1.6), neck=(cx + 0.05, cy - 0.05, zb + 2.6), head=(cx + 0.1, cy - 0.15, zb + 2.95),
       shL=(cx - 0.05, cy + 0.38, zb + 2.45), shR=(cx + 0.1, cy - 0.42, zb + 2.45),
       haL=(cx + 0.35, cy - 0.2, zb + 1.5), haR=(cx + 0.6, cy - 0.35, zb + 1.6),
       hipL=(cx, cy + 0.17, zb + 1.5), hipR=(cx, cy - 0.17, zb + 1.5),
       anL=(cx + 0.2, cy + 0.2, zb + 0.12), anR=(cx - 0.25, cy - 0.15, zb + 0.12),
       polesA=((0, 0, -1), (0, 0, -1)), polesL=((1, 0, 0.1), (1, 0, 0.1)), head_kind='cap', torso_w=1.2, head_r=1.0)
blob(B, Vector((cx + 0.7, cy - 0.55, zb + 1.55)), 0.2, 0.2, 0.2, seg=6, rings=3)    # ядро в руках
tube(B, [Vector((-0.6, 2.4, zb + 0.4)), Vector((-0.3, 2.35, zb + 1.9)), Vector((0.1, 2.3, zb + 2.7))], [(0.5, 0.5), (0.45, 0.45), (0.5, 0.5)], 10)  # ствол орудия
lathe(B, Vector((-0.6, 2.8, zb)), [(0.7, 0.0), (0.75, 0.5), (0.7, 0.9), (0.0, 0.9)], 10, cap=False)   # габион
done('kornilov_malahov', __file__, 1796.7, 1443.4, 'Памятник адмиралу В. А. Корнилову (Малахов курган)')
