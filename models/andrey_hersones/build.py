# Памятник апостолу Андрею Первозванному (Херсонес Таврический), по фото Викисклада (refs/).
#
#   blender -b --python models/andrey_hersones/build.py -- [glb]
#
# Бронзовый апостол в длинном гиматии: правая рука вытянута в сторону (благословляющий жест), в левой — высокий
# крест-посох. Стоит на необработанной гранитной глыбе («Святый апостоле Андрее, моли Бога о нас»), а та — на
# низком основании, облицованном плоским камнем.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = -2579.8, 596.1
origin(X0, Z0)
set_rot(world_rot(-1.0, 0.0))
COL['wall3'] = ((0.20, 0.19, 0.17), 0.5)
COL['metal'] = ((0.14, 0.13, 0.11), 0.5)
COL['wall2'] = ((0.62, 0.61, 0.58), 0.85)       # светлый шершавый гранит
COL['stone'] = ((0.62, 0.55, 0.45), 0.9)       # плитняк
B = 'wall3'; G = 'wall2'
F0 = FR()
import random
rnd = random.Random(5)
box('stone', F0, -4.0, 4.0, -2.2, 2.2, -0.3, 0.7)
rings = []
for z, rx, ry in ((0.7, 1.55, 1.75), (1.1, 1.65, 1.85), (1.7, 1.6, 1.8), (2.3, 1.4, 1.55), (2.55, 1.25, 1.4)):
    ph = rnd.random() * 5
    rings.append((Vector((0, 0, z)), rx, ry, (lambda p: (lambda t: 1 + 0.08 * math.sin(3 * t + p) + 0.04 * math.sin(6 * t + 2)))(ph)))
skirt(G, rings, seg=12, caps=(False, True))
plate('metal', FR(0, 0, -90), 0.4, 1.4, 1.52, 1.3, 1.8, lines=2, seed=51, pr=0.02)
box('wall3', F0, -0.75, 0.75, -0.7, 0.7, 2.5, 2.62)
z0 = 2.62
fg = Fig(3.4, face=(1, 0, 0), bulk=1.2, seg=8)
person(B, fg, pel=(0.0, 0, z0 + 1.72), neck=(0.02, 0, z0 + 2.8), head=(0.05, 0, z0 + 3.12),
       shL=(0.0, 0.46, z0 + 2.62), shR=(0.0, -0.46, z0 + 2.62),
       haL=(0.38, 0.55, z0 + 1.95), haR=(0.25, -1.3, z0 + 2.7),
       hipL=(0, 0.16, z0 + 1.6), hipR=(0, -0.16, z0 + 1.6),
       anL=(0.05, 0.17, z0 + 0.15), anR=(0.0, -0.17, z0 + 0.15),
       polesA=((0.2, 0.2, -1), (0.1, 0, -1)), polesL=((1, 0, 0), (1, 0, 0)),
       head_kind='hair', torso_w=1.25, head_r=1.1, arm_r=1.2, leg_r=0.8)
# гиматий: длинные складчатые полы, накидка через плечо
skirt(B, [(Vector((0.0, 0, z0 + 1.9)), 0.38, 0.34, None), (Vector((0.0, 0, z0 + 1.2)), 0.44, 0.42, lambda t: 1 + 0.06 * math.sin(5 * t)),
          (Vector((0.0, 0, z0 + 0.5)), 0.5, 0.5, lambda t: 1 + 0.09 * math.sin(6 * t + 1)), (Vector((0.0, 0, z0 + 0.04)), 0.54, 0.54, None)], seg=12, caps=(False, True))
tube(B, [P(0.1, 0.45, z0 + 2.7), P(0.22, 0.2, z0 + 1.7), P(0.2, -0.15, z0 + 0.9)], [0.2, 0.22, 0.2], 6)
# крест-посох в левой руке
beam(B, P(0.4, 0.58, z0 + 0.05), P(0.4, 0.58, z0 + 4.3), 0.09, 0.09)
beam(B, P(0.4, 0.58 - 0.5, z0 + 3.95), P(0.4, 0.58 + 0.5, z0 + 3.95), 0.08, 0.08)
done('andrey_hersones', __file__, -2579.8, 596.1, 'Памятник апостолу Андрею Первозванному (Херсонес)')
