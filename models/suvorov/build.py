# Памятник-бюст А. В. Суворову (ул. Сергеева-Ценского, у лестницы), Севастополь.
#
#   blender -b --python models/suvorov/build.py -- [glb]
#
# По фото Викисклада (refs/r0, издали): бронзовый бюст полководца (парик с косицей, мундир с эполетами и лентой)
# на высоком узком светло-сером гранитном столбе с бронзовой плитой, на низком основании в газоне;
# по сторонам — чугунные фонари. Размеры оценены по высоте фонарей (~3 м): всего ≈4,5 м.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = 138.9, 1147.9
origin(X0, Z0)
set_rot(world_rot(-0.8, -0.6))
COL['wall3'] = ((0.14, 0.16, 0.15), 0.5)
COL['metal'] = ((0.10, 0.11, 0.10), 0.5)
COL['wall2'] = ((0.62, 0.62, 0.58), 0.6)
COL['stone'] = ((0.55, 0.54, 0.50), 0.9)
B = 'wall3'; G = 'wall2'
F0 = FR()
box('stone', F0, -2.2, 2.2, -2.2, 2.2, -0.3, 0.05)
frustum(G, F0, (-0.95, 0.95, -0.95, 0.95), (-0.8, 0.8, -0.8, 0.8), 0.0, 0.7)
box(G, F0, -0.7, 0.7, -0.7, 0.7, 0.7, 0.85)
frustum(G, F0, (-0.52, 0.52, -0.52, 0.52), (-0.42, 0.42, -0.42, 0.42), 0.85, 3.2)       # узкий столб
box(G, F0, -0.5, 0.5, -0.5, 0.5, 3.2, 3.3)
box(G, F0, -0.58, 0.58, -0.58, 0.58, 3.3, 3.5)
plate('metal', FR(0, 0, -90), -0.22, 0.22, 0.47, 2.1, 2.8, lines=4, seed=31, pr=0.02)
bust(B, 3.5, k=1.2)
tube(B, [P(-0.1, 0, 3.5 + 0.7 * 1.2), P(-0.22, 0, 3.5 + 0.55 * 1.2)], [0.03, 0.05], 5)    # косица
for sg in (-1, 1):                                                                          # фонари
    c = (0.2, sg * 1.6)
    lathe(B, P(c[0], c[1], 0), [(0.14, 0), (0.1, 0.4), (0.06, 0.6), (0.05, 2.7)], 6, cap=False)
    blob('trim_s', Vector((c[0], c[1], 2.95)), 0.22, 0.22, 0.26, seg=8, rings=4)
done('suvorov', __file__, 138.9, 1147.9, 'Памятник-бюст А. В. Суворову')
