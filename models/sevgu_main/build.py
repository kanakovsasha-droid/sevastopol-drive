# СевГУ, главный корпус на ул. Университетской, 33 (Севастопольский
# приборостроительный институт, построен в 1970-х) — модель с нуля.
#
#   blender -b --python models/sevgu_main/build.py -- [glb]
#
# План — контур OSM way 93081482 как есть: «игрек» из трёх крыльев по 15 м
# шириной (западное, северное, юго-восточное) со скруглёнными стыками.
# Фасады — фото Викисклада (File:SevSu.jpg, File:СНТУ. Учебный корпус.
# Студгородок..JPG, File:Sevntu vhod.jpg) и pastvu (1075048, 1963588, 1655308 —
# аэрофото 1988, 1310241): белый бетон; первый этаж — стеклянный, утоплен под
# нависающие этажи и стоит на опорах; выше семь этажей ленточных окон в
# сетке вертикальных рёбер-солнцерезов и полок по этажам; торцы крыльев
# глухие с узкой полосой окон лестницы; на стыке — высокий глухой объём с
# эмблемой СевГУ. Что наугад — NOTES.md. Ноль высоты — площадь у входа.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from kit import *

X0, Z0 = -3952.0, 2412.0
origin(X0, Z0)

COL['wall'] = ((0.92, 0.91, 0.88), 0.9)       # белый бетон и штукатурка
COL['trim'] = ((0.95, 0.94, 0.92), 0.85)      # рёбра, полки, козырёк
COL['wall2'] = ((0.86, 0.85, 0.82), 0.9)      # глухие стены башни (чуть темнее в тени)
COL['stone'] = ((0.62, 0.62, 0.60), 0.9)      # цоколь, ступени
COL['roof'] = ((0.50, 0.50, 0.49), 0.9)       # плоская кровля
COL['glass'] = ((0.16, 0.20, 0.25), 0.15)
COL['metal'] = ((0.25, 0.26, 0.27), 0.5)
COL['wood'] = ((0.10, 0.33, 0.66), 0.5)       # синий эмблемы (дерева в доме нет)

# контур OSM (мир x, z), без зубца-тамбура у юго-восточного крыла
POLY = [(-3926.6, 2341.7), (-3912.6, 2348.2), (-3929.4, 2381.2), (-3931.5, 2386.1), (-3932.2, 2390.4),
        (-3932.7, 2394.5), (-3932.4, 2398.4), (-3931.3, 2402.0), (-3908.5, 2437.8), (-3902.0, 2448.0),
        (-3894.3, 2460.1), (-3907.0, 2468.8), (-3917.9, 2452.8), (-3940.8, 2418.5),
        (-3944.9, 2413.0), (-3950.0, 2409.0), (-3954.5, 2406.6), (-3959.9, 2404.9), (-3963.4, 2404.7),
        (-3967.3, 2404.9), (-3997.7, 2407.2), (-3998.9, 2392.0), (-3967.7, 2389.9), (-3963.0, 2389.1),
        (-3957.2, 2387.3), (-3951.7, 2383.9), (-3946.8, 2379.4)]
ENDS = {0, 10, 20}            # рёбра-торцы крыльев: i → i+1
GROUND = -3.0
G1 = 4.2                      # верх первого (стеклянного) этажа
FH = 3.3                      # этаж
NF = 7                        # этажей над первым
TOP = G1 + NF * FH            # 27.3
PAR = TOP + 0.9

def quad(m, F, u0, u1, z0, z1, d, hint=None):
    face(m, [F.p(u0, d, z0), F.p(u1, d, z0), F.p(u1, d, z1), F.p(u0, d, z1)], hint if hint is not None else F.N())

def plan_pts(poly):
    return [W(*p) for p in poly]

P = plan_pts(POLY)
n = len(P)
area = sum(P[i].x * P[(i + 1) % n].y - P[(i + 1) % n].x * P[i].y for i in range(n)) / 2
CCW = area > 0

def frame_edge(i):
    a, b = P[i], P[(i + 1) % n]
    u = (b - a).normalized()
    nrm = Vector((u.y, -u.x)) if CCW else Vector((-u.y, u.x))   # наружу
    return Frame(a, u, nrm), (b - a).length

def inset(pts, d):
    """Контур, сдвинутый внутрь на d (стыки — на биссектрисах)."""
    out = []
    m = len(pts)
    for i in range(m):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % m]
        e0 = (p1 - p0).normalized(); e1 = (p2 - p1).normalized()
        n0 = Vector((-e0.y, e0.x)) if CCW else Vector((e0.y, -e0.x))   # внутрь
        n1 = Vector((-e1.y, e1.x)) if CCW else Vector((e1.y, -e1.x))
        bis = (n0 + n1)
        k = d / max(0.35, bis.length / 2) if bis.length > 1e-6 else d
        out.append(p1 + bis.normalized() * min(k, d * 2.5))
    return out

# ------------------------------------------------------------------ масса
# перекрытие над стеклянным первым этажом (низ нависающей части) и кровля
face('trim', [Vector((p.x, p.y, G1)) for p in P], -UP)
face('roof', [Vector((p.x, p.y, TOP)) for p in P], UP)

# первый этаж: витраж в 1.6 м за линией фасада, опоры по линии фасада
PI = inset(P, 1.6)
for i in range(n):
    a, b = PI[i], PI[(i + 1) % n]
    L = (b - a).length
    if L < 0.05: continue
    u = (b - a).normalized()
    F = Frame(a, u, Vector((u.y, -u.x)) if CCW else Vector((-u.y, u.x)))
    quad('glass', F, 0, L, 0.3, G1 - 0.35, 0)
    quad('wall', F, 0, L, G1 - 0.35, G1, 0)
    quad('stone', F, 0, L, GROUND, 0.3, 0)
    k = 0.0
    while k < L - 0.3:
        quad('metal', F, k - 0.04, k + 0.04, 0.3, G1 - 0.35, 0.02)
        k += 2.0

# ------------------------------------------------------------------ фасады
def fins_facade(F, L):
    """Ряды окон в сетке рёбер: стена, ленты стекла, полки по этажам, рёбра."""
    quad('wall', F, 0, L, G1, PAR, 0)
    bays = max(1, round(L / 3.1))
    step = L / bays
    for f in range(NF):
        z0 = G1 + f * FH
        quad('glass', F, 0.1, L - 0.1, z0 + 0.95, z0 + 2.75, 0.02)
        # полка-козырёк над окнами этажа (сверху и снизу видна)
        z1 = z0 + FH
        a, b = -0.05, L + 0.05
        quad('trim', F, a, b, z1 - 0.18, z1, 0.75)
        face('trim', [F.p(a, 0, z1), F.p(b, 0, z1), F.p(b, 0.75, z1), F.p(a, 0.75, z1)], UP)
        face('trim', [F.p(a, 0, z1 - 0.18), F.p(b, 0, z1 - 0.18), F.p(b, 0.75, z1 - 0.18), F.p(a, 0.75, z1 - 0.18)], -UP)
        # переплёты окон: по два на пролёт
        for k in range(bays):
            for t in (0.5,):
                u = step * (k + t)
                quad('trim', F, u - 0.04, u + 0.04, z0 + 0.95, z0 + 2.75, 0.04)
    # подоконная полка первого жилого этажа и рёбра-солнцерезы на всю высоту
    quad('trim', F, -0.05, L + 0.05, G1 - 0.05, G1 + 0.2, 0.75)
    for k in range(bays + 1):
        u = min(max(step * k, 0.1), L - 0.1)
        # ребро — клин: у стены шире, к краю уже (как на фото — «пила»)
        face('trim', [F.p(u - 0.12, 0.0, G1), F.p(u - 0.12, 0.95, G1), F.p(u - 0.12, 0.95, TOP + 0.2), F.p(u - 0.12, 0.0, TOP + 0.2)], -F.U())
        face('trim', [F.p(u + 0.12, 0.0, G1), F.p(u + 0.12, 0.95, G1), F.p(u + 0.12, 0.95, TOP + 0.2), F.p(u + 0.12, 0.0, TOP + 0.2)], F.U())
        quad('trim', F, u - 0.12, u + 0.12, G1, TOP + 0.2, 0.95)
        face('trim', [F.p(u - 0.12, 0, G1), F.p(u + 0.12, 0, G1), F.p(u + 0.12, 0.95, G1), F.p(u - 0.12, 0.95, G1)], -UP)
        # опора первого этажа под каждым вторым ребром
        if k % 2 == 0:
            box('wall', F, u - 0.3, u + 0.3, -0.3, 0.3, GROUND, G1)
    # парапет
    box('trim', F, -0.05, L + 0.05, -0.25, 0.1, PAR, PAR + 0.12)

def end_facade(F, L):
    """Глухой торец крыла с узкой полосой окон лестницы."""
    quad('wall', F, 0, L, G1, PAR, 0)
    c = L / 2
    for f in range(NF):
        z0 = G1 + f * FH
        quad('glass', F, c - 0.9, c + 0.9, z0 + 0.6, z0 + 2.9, 0.02)
    quad('trim', F, c - 1.05, c - 0.9, G1 + 0.4, TOP - 0.2, 0.08)
    quad('trim', F, c + 0.9, c + 1.05, G1 + 0.4, TOP - 0.2, 0.08)
    for a, b in ((0, 0.6), (L - 0.6, L)):
        box('wall', F, a, b, -0.6, 0, GROUND, G1)
    box('trim', F, -0.05, L + 0.05, -0.25, 0.1, PAR, PAR + 0.12)

for i in range(n):
    F, L = frame_edge(i)
    if L < 0.05: continue
    if i in ENDS:
        end_facade(F, L)
    elif L >= 6.0:
        fins_facade(F, L)
    else:
        # короткие рёбра скруглений: стена, стекло и полки без рёбер
        quad('wall', F, 0, L, G1, PAR, 0)
        for f in range(NF):
            z0 = G1 + f * FH
            quad('glass', F, 0, L, z0 + 0.95, z0 + 2.75, 0.02)
            z1 = z0 + FH
            quad('trim', F, -0.05, L + 0.05, z1 - 0.18, z1, 0.75)
            face('trim', [F.p(-0.05, 0, z1), F.p(L + 0.05, 0, z1), F.p(L + 0.05, 0.75, z1), F.p(-0.05, 0.75, z1)], UP)
            face('trim', [F.p(-0.05, 0, z1 - 0.18), F.p(L + 0.05, 0, z1 - 0.18), F.p(L + 0.05, 0.75, z1 - 0.18), F.p(-0.05, 0.75, z1 - 0.18)], -UP)
        quad('trim', F, -0.05, L + 0.05, G1 - 0.05, G1 + 0.2, 0.75)
        box('trim', F, -0.05, L + 0.05, -0.25, 0.1, PAR, PAR + 0.12)
        if L > 2.0:                  # ребро и на скруглении — сетка не рвётся
            box('trim', F, L / 2 - 0.12, L / 2 + 0.12, 0, 0.95, G1, TOP + 0.2)

# ------------------------------------------------------------------ башня на стыке
# Высокий глухой объём (фото SevSu.jpg — справа от изогнутого фасада; аэрофото
# 1988 — над стыком крыльев): на два этажа выше, с полосами окон и эмблемой.
TC = W(-3941.0, 2397.0)
ax = (W(-3894.3, 2460.1) - W(-3931.3, 2402.0)).normalized()     # вдоль юго-восточного крыла
side = Vector((ax.y, -ax.x))
FT = Frame(TC, ax, side)
TW, TD, TH = 8.0, 7.5, TOP + 2 * FH + 1.0
box('wall2', FT, -TW, TW, -TD, TD, TOP - 1.0, TH)
box('trim', FT, -TW - 0.15, TW + 0.15, -TD - 0.15, TD + 0.15, TH, TH + 0.35)
for s in (-1, 1):                    # полосы окон лестниц на длинных сторонах
    Fs = Frame(TC + side * (TD * s), ax * s, side * s)
    for u0 in (-TW + 1.2, TW - 3.0):
        for f in range(2):
            z0 = TOP + f * FH
            quad('glass', Fs, u0, u0 + 1.8, z0 + 0.7, z0 + 2.8, 0.02)
for s in (-1, 1):
    Fs = Frame(TC + ax * (TW * s), side * -s, ax * s)
    quad('glass', Fs, -1.0, 1.0, TOP + 0.6, TH - 0.8, 0.02)
# эмблема: синий круг с белой стрелой на стороне, обращённой к площади
sw = (W(-3960.0, 2430.0) - TC)
Fe = Frame(TC + side * TD, -ax, side) if sw.dot(side) > 0 else Frame(TC - side * TD, ax, -side)
zc, r = TOP + 4.0, 2.3
ring = [(r * math.cos(2 * math.pi * k / 24), zc + r * math.sin(2 * math.pi * k / 24)) for k in range(24)]
face('wood', [Fe.p(u, 0.06, z) for u, z in ring], Fe.N())
face('trim', [Fe.p(-1.3, 0.09, zc - 0.9), Fe.p(1.4, 0.09, zc + 0.25), Fe.p(-0.6, 0.09, zc + 1.4)], Fe.N())
face('wood', [Fe.p(-0.55, 0.1, zc - 0.1), Fe.p(1.0, 0.1, zc + 0.2), Fe.p(-0.4, 0.1, zc + 0.9)], Fe.N())

# ------------------------------------------------------------------ вход
# Козырёк на мраморных опорах у юго-западной стороны стыка, к площади
# (File:Sevntu vhod.jpg): плита на двух пилонах, крыльцо в две ступени.
a, b = W(-3954.5, 2406.6), W(-3944.9, 2413.0)
u = (b - a).normalized(); nv = Vector((u.y, -u.x)) if CCW else Vector((-u.y, u.x))
FE = Frame((a + b) / 2, u, nv)
box('trim', FE, -6.0, 6.0, -1.6, 3.6, 3.4, 4.0)
for uu in (-2.5, 2.5):
    box('stone', FE, uu - 0.3, uu + 0.3, 2.4, 3.0, 0.3, 3.4)
box('stone', FE, -5.0, 5.0, -1.6, 4.4, GROUND, 0.3)
box('stone', FE, -5.0, 5.0, 4.4, 5.0, GROUND, 0.15)
quad('metal', FE, -1.5, 1.5, 0.3, 2.8, -1.55)

finish('sevgu_main', __file__)
