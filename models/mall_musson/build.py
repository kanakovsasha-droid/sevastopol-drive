# ТРЦ «Муссон», ул. Вакуленчука, 29 — модель с нуля.
#
#   blender -b --python models/mall_musson/build.py -- [glb]
#
# Перестроенный цех завода «Муссон»: серая панельная коробка 240 × 145 м под
# шестью пологими двускатными кровлями, главный фасад на северо-запад, к
# парку «Каменный цветок». Над входом — красные буквы «МУССОН / ТОРГОВЫЙ
# ЦЕНТР» на ферме, под ними медиаэкраны, справа шар с буквами DNS, синий
# козырёк по первому этажу. Что откуда — NOTES.md.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mall_kit import *

# Опорные точки контура OSM w93081676 (мир x, z)
A = (-2961.6, 3095.7)    # западный угол главного фасада
B = (-2810.3, 3026.1)    # главный фасад упирается в северный выступ
N1, N2 = (-2834.0, 2975.1), (-2767.2, 2944.4)   # северный выступ
G = (-2743.5, 2995.7)    # продолжение линии фасада за выступом
E = (-2682.6, 3127.4)    # восточный угол
Fc = (-2900.6, 3227.6)   # южный угол
INSIDE = (-2830, 3110)

ENTA = 101.0                                  # ось главного входа от угла A (панорама 2021)
LEN0 = ((G[0] - A[0]) ** 2 + (G[1] - A[1]) ** 2) ** 0.5
# начало модели — у входа на уровне площади
ox, oz = A[0] + (G[0] - A[0]) * ENTA / LEN0, A[1] + (G[1] - A[1]) * ENTA / LEN0
origin(ox, oz)
# u растёт вправо для того, кто стоит на площади лицом к входу: от G к A
FR, LEN = frame_lr(A, G, INSIDE)
ENT = LEN - ENTA
DEPTH = (W(*E) - W(*G)).length                # ширина корпуса, ~145 м

COL['wall'] = ((0.74, 0.75, 0.77), 0.7)      # серые сэндвич-панели
COL['wall2'] = ((0.66, 0.68, 0.70), 0.7)     # швы и тяги
COL['roof'] = ((0.60, 0.62, 0.64), 0.55)     # профлист кровель
COL['stone'] = ((0.55, 0.55, 0.53), 0.9)
mat('canopy', (0.10, 0.27, 0.62), 0.5)        # синий козырёк
mat('red', (0.80, 0.09, 0.10), 0.45)          # буквы «МУССОН»
mat('screen', (0.06, 0.08, 0.12), 0.25)       # медиаэкраны
mat('white', (0.95, 0.95, 0.94), 0.5)
mat('globe', (0.86, 0.82, 0.74), 0.5)         # шар на кровле
mat('green', (0.36, 0.72, 0.16), 0.5)
mat('dkgreen', (0.07, 0.20, 0.10), 0.6)
mat('blue', (0.12, 0.20, 0.62), 0.5)
mat('gold', (0.78, 0.62, 0.30), 0.5)
lod_keep('red', 'canopy', 'screen', 'globe')

GROUND = -3.0
H = 11.0           # верх стен цеха
HF = 13.0          # парапет главного фасада
RISE = 2.4         # подъём пологих кровель

# ------------------------------------------------------------------ корпус
prism_world('wall', [A, B, N1, N2, G, E, Fc], GROUND, H, top=True, roof='roof')
# главный фасад выше — парапет-аттик по всей длине до выступа
LB = (W(*B) - W(*A)).length
UB = LEN - LB                 # u, где главный фасад упирается в выступ
box('wall', FR, UB, LEN, -1.2, 0, H - 0.5, HF)
box('wall2', FR, UB - 0.1, LEN + 0.1, -1.3, 0.12, HF, HF + 0.25)
# горизонтальные швы панелей главного фасада
for z in (1.2 * k for k in range(1, 11)):
    if z < 4.6: continue
    box('wall2', FR, UB, LEN, 0, 0.05, z - 0.03, z + 0.03, bottom=False)

# пологие двускатные кровли вдоль фасада: шесть пролётов поперёк корпуса
NB = 6
bw = DEPTH / NB
for k in range(NB):
    d0, d1 = -k * bw, -(k + 1) * bw
    dm = (d0 + d1) / 2
    u0, u1 = 0.0, LEN
    a0, a1 = FR.p(u0, d0, H), FR.p(u1, d0, H)
    b0, b1 = FR.p(u0, d1, H), FR.p(u1, d1, H)
    r0, r1 = FR.p(u0, dm, H + RISE), FR.p(u1, dm, H + RISE)
    face('roof', [a0, a1, r1, r0], FR.N() + UP * 4)
    face('roof', [b1, b0, r0, r1], -FR.N() + UP * 4)
    face('wall', [a0, r0, b0], -FR.U())
    face('wall', [a1, b1, r1], FR.U())
    beam('wall2', r0 + UP * 0.08, r1 + UP * 0.08, 0.5, 0.18)     # конёк
# северный выступ — плоская кровля с парапетом
flat_roof('roof', [B, N1, N2, G], H + 0.2, edge='wall2')

# цоколь
prism_world('stone', [A, B, N1, N2, G, E, Fc], GROUND, 0.45, top=False)

# ------------------------------------------------------------------ главный фасад
F = FR
# первый этаж: витрины под синим козырьком
C0, C1 = ENT - 55.0, ENT + 42.0
curtain(F, C0, C1, 0.0, 4.2, 0.06, du=3.0, dz=4.2)
box('canopy', F, C0 - 1, C1 + 1, 0, 5.2, 4.4, 5.25)                  # козырёк
box('canopy', F, C0 - 1, C1 + 1, 5.0, 5.35, 4.0, 5.35)               # кромка
for u in range(int(C0) + 4, int(C1), 12):                            # тяги
    beam('metal', F.p(u, 5.0, 4.4), F.p(u, 0.1, 7.5), 0.12)
# вход: стеклянный тамбур
box('glass', F, ENT - 4.5, ENT + 4.5, 0.06, 2.2, 0, 3.6)
box('metal', F, ENT - 4.6, ENT + 4.6, 0.0, 2.3, 3.6, 3.85)
# слева от входа — «Золотая балка» (тёмный короб), справа — «Империя сумок»
board(F, ENT - 33, ENT - 12, 2.9, 4.15, 0.08, 'screen', depth=0.25)
text('white', F, 'ЗОЛОТАЯ БАЛКА', ENT - 22.5, 3.3, 0.6, 0.33, depth=0.06)
board(F, ENT + 7, ENT + 27, 2.6, 4.15, 0.08, 'white', depth=0.35)
text('screen', F, 'ИМПЕРИЯ СУМОК', ENT + 17, 3.1, 0.6, 0.43, depth=0.06)

# медиаэкраны над входом: большой в середине, два поменьше по бокам
board(F, ENT - 9.5, ENT + 9.5, 5.6, 11.6, 0.1, 'screen', depth=0.5)
board(F, ENT - 18.5, ENT - 10.2, 6.2, 11.2, 0.1, 'screen', depth=0.4)
board(F, ENT + 10.2, ENT + 18.5, 6.2, 11.2, 0.1, 'screen', depth=0.4)
for s in (-1, 1):   # полосы картинки на боковых экранах — жёлтое и красное
    c = ENT + s * 14.35
    box('gold', F, c - 3.9, c + 3.9, 0.5, 0.56, 8.0, 9.6, bottom=False)
    box('red', F, c - 3.9, c + 3.9, 0.5, 0.56, 6.6, 7.4, bottom=False)
box('blue', F, ENT - 9.0, ENT + 9.0, 0.6, 0.66, 7.0, 10.6, bottom=False)

# «Большое Яблоко» — щит слева
YU = ENT - 27.0
board(F, YU - 4, YU + 4, 5.6, 11.4, 0.1, 'dkgreen', depth=0.35)
box('red', F, YU - 3.6, YU + 3.6, 0.45, 0.5, 10.4, 11.1, bottom=False)
text('green', F, 'Большое', YU, 8.4, 1.1, 0.45, depth=0.08, fnt='Arial Bold Italic.ttf', width=6.6)
text('green', F, 'Яблоко', YU, 6.7, 1.4, 0.45, depth=0.08, fnt='Arial Bold Italic.ttf', width=6.8)

# ------------------------------------------------------------------ крышные буквы
LZ = HF + 1.6                     # низ букв «МУССОН»
truss(F, ENT - 18, ENT + 18, HF + 0.25, LZ + 5.0, -0.6, bays=13)
text('red', F, 'МУССОН', ENT, LZ, 4.8, -0.3, depth=0.35, width=33.0, spacing=1.15)
text('red', F, 'ТОРГОВЫЙ  ЦЕНТР', ENT + 0.5, HF + 0.35, 1.05, -0.3, depth=0.2, width=29.0, spacing=1.6)
# шар справа и буквы DNS перед ним
GU = ENT + 26.0
sphere('globe', F.p(GU, -3.5, HF + 4.1), 3.6, seg=18, rings=10)
box('metal', F, GU - 0.4, GU + 0.4, -3.9, -3.1, HF, HF + 1.0)
truss(F, GU - 6.5, GU + 6.5, HF + 0.25, HF + 4.2, -0.6, bays=5)
text('red', F, 'DNS', GU, HF + 0.6, 3.4, -0.3, depth=0.35, width=12.0)
# «лэтуаль» — светлые буквы на ферме слева
LU = ENT - 33.0
truss(F, LU - 10, LU + 10, HF + 0.25, HF + 3.0, -0.6, bays=7)
text('white', F, 'лэтуаль', LU, HF + 0.6, 2.2, -0.3, depth=0.25, width=18.0)
# voltmart — справа на кровле: красный знак и синие буквы
VU = ENT + 50.0
truss(F, VU - 12, VU + 12, HF + 0.25, HF + 3.4, -0.6, bays=8)
disc('red', F, VU - 9.0, HF + 2.0, 1.7, -0.3, depth=0.25)
text('white', F, 'ш', VU - 9.0, HF + 1.3, 1.0, -0.06, depth=0.1)
text('blue', F, 'voltmart', VU + 2.0, HF + 0.9, 1.9, -0.3, depth=0.25, width=17.0)

# ------------------------------------------------------------------ северный выступ и боковые
FN, LN = frame_from(B, N1, INSIDE)            # западная стена выступа
box('canopy', FN, 4, LN - 4, 0, 3.0, 3.6, 4.1)
curtain(FN, 6, LN - 6, 0, 3.5, 0.06, du=3.0, dz=3.5)
FE, LE = frame_from(Fc, A, INSIDE)            # юго-западный торец
for k in range(5):                              # ворота разгрузки
    u = 20 + k * 22
    box('wall2', FE, u, u + 4.5, 0, 0.12, 0, 4.5)
print('НАЧАЛО', round(ox, 1), round(oz, 1))
finish('mall_musson', __file__)
