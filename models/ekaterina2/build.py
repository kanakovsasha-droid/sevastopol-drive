# Памятник Екатерине II в Екатерининском сквере (ул. Ленина), Севастополь.
#
#   blender -b --python models/ekaterina2/build.py -- [glb]
#
# По фото Викисклада (refs/): бронзовая императрица в платье с мантией, лентой и
# скипетром на ступенчатом постаменте из красно-коричневого гранита. Фигура смотрит
# в сторону от Штаба ЧФ (на ВСВ). Ноль высоты — плитка у подножия.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = -19.3, 363.6
origin(X0, Z0)
set_rot(world_rot(0.88, -0.46))
COL['wall3'] = ((0.16, 0.15, 0.13), 0.5)       # тёмная бронза
COL['metal'] = ((0.12, 0.11, 0.09), 0.5)
COL['wall2'] = ((0.45, 0.25, 0.20), 0.35)      # красно-коричневый гранит (Капустинский)
COL['stone'] = ((0.62, 0.60, 0.57), 0.9)
B = 'wall3'; G = 'wall2'
F0 = FR()

# ------------------------------------------------------------------ постамент
box('stone', F0, -5.2, 5.2, -5.2, 5.2, -0.4, 0.02)                    # мощение у подножия
frustum(G, F0, (-3.7, 3.7, -3.7, 3.7), (-3.4, 3.4, -3.4, 3.4), -0.3, 0.5)
frustum(G, F0, (-2.7, 2.7, -2.7, 2.7), (-2.0, 2.0, -2.0, 2.0), 0.5, 1.15)
box(G, F0, -1.55, 1.55, -1.55, 1.55, 1.15, 1.6)
lathe(G, Vector((0, 0, 0)), [(1.45, 1.6), (1.35, 1.7), (1.22, 1.95), (1.05, 2.15), (0.92, 2.25), (0.92, 4.15)], 24, cap=False)
# колонна-барабан с поясами, шестигранный блок с плитами
lathe(G, Vector((0, 0, 0)), [(0.92, 4.15), (1.0, 4.15), (1.0, 4.2)], 24, cap=False)
hexpts = [(1.15 * math.cos(math.radians(30 + 60 * k)), 1.15 * math.sin(math.radians(30 + 60 * k))) for k in range(6)]
prism_plan(G, F0, hexpts, 4.15, 5.4, True)
lathe(G, Vector((0, 0, 0)), [(0.95, 5.4), (0.95, 5.45), (0.78, 5.62), (0.80, 5.85), (0.80, 5.95), (0.0, 5.95)], 24, cap=False)
lathe(B, Vector((0, 0, 0)), [(0.84, 5.95), (0.84, 6.25), (0.0, 6.25)], 24, cap=False)
# бронзовые плиты на гранях шестигранника: вензель на лицевой, текст на боковой, карта на другой
ap = 1.15 * math.cos(math.radians(30))
for k, kind in ((0, 'cart'), (1, 'text'), (5, 'map')):
    ang = math.radians(60 * k)
    Fk = FR(0, 0, 60 * k - 90)
    if kind == 'cart':
        for dd, hw, hh in ((0.0, 0.48, 0.5), (0.04, 0.40, 0.42)):
            box('metal', Fk, -hw, hw, ap - 0.01 + dd, ap + 0.03 + dd, 4.8 - hh, 4.8 + hh)
        box('metal', Fk, -0.07, 0.07, ap + 0.07, ap + 0.10, 4.6, 5.0)
    elif kind == 'text':
        plate('metal', Fk, -0.55, 0.55, ap - 0.01, 4.45, 5.25, lines=7, seed=5, pr=0.01)
    else:
        box('wall3', Fk, -0.45, 0.45, ap - 0.01, ap + 0.015, 4.5, 5.2)

# ------------------------------------------------------------------ статуя (рост 3,2 м, база 6,25)
z0 = 6.25
fg = Fig(3.05, face=(1, 0, 0), bulk=1.0, seg=10)
person(B, fg, pel=(0.0, 0, z0 + 1.55), neck=(0.02, 0, z0 + 2.58), head=(0.05, 0, z0 + 2.9),
       shL=(0.0, 0.40, z0 + 2.45), shR=(0.0, -0.40, z0 + 2.45),
       haL=(0.55, 1.0, z0 + 1.85), haR=(0.22, -0.52, z0 + 1.45),
       hipL=(0, 0.14, z0 + 1.45), hipR=(0, -0.14, z0 + 1.45),
       anL=(0.0, 0.14, z0 + 0.15), anR=(0.0, -0.14, z0 + 0.15),
       polesA=((0.5, 0.3, -0.4), (-0.2, -0.3, -0.7)), polesL=((1, 0, 0), (1, 0, 0)),
       head_kind='hair', torso_w=1.3, head_r=1.05, arm_r=1.15, leg_r=0.3)
# платье в пол с фижмами и складками
skirt(B, [(Vector((0.0, 0, z0 + 1.72)), 0.30, 0.34, None),
          (Vector((0.0, 0, z0 + 1.2)), 0.38, 0.44, lambda t: 1 + 0.05 * math.sin(6 * t)),
          (Vector((0.0, 0, z0 + 0.7)), 0.46, 0.54, lambda t: 1 + 0.07 * math.sin(7 * t + 0.5)),
          (Vector((0.0, 0, z0 + 0.02)), 0.54, 0.64, lambda t: 1 + 0.09 * math.sin(8 * t + 1.0))], seg=20, caps=(False, True))
# мантия, ниспадающая за плечами
skirt(B, [(Vector((-0.20, 0, z0 + 2.45)), 0.22, 0.52, None),
          (Vector((-0.30, 0, z0 + 1.6)), 0.26, 0.64, lambda t: 1 + 0.06 * math.sin(5 * t)),
          (Vector((-0.38, 0, z0 + 0.55)), 0.30, 0.74, lambda t: 1 + 0.08 * math.sin(6 * t)),
          (Vector((-0.36, 0, z0 + 0.04)), 0.32, 0.78, None)], seg=16, caps=(False, False))
# лента через плечо и орденская звезда
beam('metal', P(0.34, 0.30, z0 + 2.40), P(0.40, -0.18, z0 + 1.58), 0.09, 0.03)
blob('metal', Vector((0.34, 0.2, z0 + 2.0)), 0.04, 0.1, 0.1, seg=8, rings=3)
# скипетр в правой руке
tube('metal', [Vector((0.24, -0.56, z0 + 0.02)), Vector((0.24, -0.56, z0 + 1.6)), Vector((0.24, -0.56, z0 + 2.55))], [0.03, 0.03, 0.045], 6)
blob('metal', Vector((0.24, -0.56, z0 + 2.62)), 0.07, 0.07, 0.09, seg=8, rings=4)
# свиток (указ) в левой руке
tube('metal', [Vector((0.55, 0.78, z0 + 1.86)), Vector((0.55, 1.35, z0 + 1.86))], [0.05, 0.05], 8)
# диадема
tube('metal', [Vector((0.05, -0.02, z0 + 3.03)), Vector((0.06, 0.02, z0 + 3.03))], [0.12, 0.12], 12, caps=(False, False))
done('ekaterina2', __file__, -19.3, 363.6, 'Памятник Екатерине II (Екатерининский сквер)')
