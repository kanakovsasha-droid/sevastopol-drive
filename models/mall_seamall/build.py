# ТЦ Sea Mall («Симол»), пр. Генерала Острякова, 260 — модель с нуля.
#
#   blender -b --python models/mall_seamall/build.py -- [glb]
#
# Главный фасад — на восток-северо-восток, к парковке у проспекта: посередине
# стеклянная ротонда с фигурами людей на витраже и вывеской SEA MALL на ферме
# (SEA синим, MALL красным, белая чайка-галочка между словами), по сторонам
# двухсветные стеклянные крылья под белым фризом с вывесками арендаторов,
# южный край — пониже, белый с красно-синей полосой («Эльдорадо»), по углам
# ещё два стеклянных барабана. Контур — OSM w218816081. Что откуда — NOTES.md.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mall_kit import *

# Дуга главной ротонды и угловых барабанов — точки контура OSM
ARC_MAIN = [(369.2, 7108.6), (371.7, 7108.2), (374.0, 7108.5), (376.1, 7109.3), (378.1, 7110.9),
            (379.5, 7112.9), (380.4, 7115.1), (380.6, 7117.6), (380.3, 7120.2), (378.2, 7123.0), (375.6, 7124.9)]
ARC_SE = [(394.2, 7178.2), (396.5, 7180.2), (398.0, 7182.3), (398.5, 7184.8), (398.3, 7187.2),
          (397.1, 7189.4), (395.1, 7191.0), (392.6, 7191.5), (390.1, 7191.4), (387.7, 7190.2)]
ARC_N = [(333.3, 7050.2), (334.1, 7048.4), (335.3, 7047.0), (337.2, 7045.7), (339.2, 7045.2),
         (341.6, 7045.3), (343.6, 7046.1), (344.9, 7047.3), (346.1, 7049.3), (346.7, 7051.6), (346.2, 7054.4)]
RC = fit_circle(ARC_MAIN)          # центр и радиус ротонды
SC = fit_circle(ARC_SE)
NC = fit_circle(ARC_N)

origin(RC[0], RC[1])               # начало — центр ротонды на уровне площади
INSIDE = (320, 7125)
P_S, P_N = (394.2, 7178.2), (346.2, 7054.4)
F, LEN = frame_lr(P_S, P_N, INSIDE)          # u: с юга на север, вправо для зрителя на парковке
U = lambda p: (W(*p) - F.o).dot(F.u)
D = lambda p: (W(*p) - F.o).dot(F.n)
uR = U(RC[:2])
uS = U((380.0, 7138.0))            # граница низкого южного корпуса

COL['wall'] = ((0.93, 0.93, 0.92), 0.6)      # белые панели
COL['wall2'] = ((0.75, 0.77, 0.79), 0.6)     # швы, серый металл
COL['roof'] = ((0.55, 0.53, 0.50), 0.85)     # битумная кровля
COL['glass'] = ((0.16, 0.30, 0.44), 0.12)    # голубоватые витражи
COL['stone'] = ((0.60, 0.60, 0.58), 0.9)
mat('blue', (0.10, 0.22, 0.60), 0.5)
mat('red', (0.83, 0.10, 0.12), 0.45)
mat('dark', (0.10, 0.10, 0.11), 0.5)
mat('pink', (0.86, 0.12, 0.52), 0.5)
mat('grey', (0.45, 0.47, 0.50), 0.5)
mat('white', (0.97, 0.97, 0.97), 0.5)
mat('figure', (0.10, 0.14, 0.20), 0.4)       # силуэты людей на витраже
lod_keep('blue', 'red', 'white')

GROUND = -3.0
HW = 12.5          # верх крыльев
HS = 10.0          # верх южного корпуса
HR = 15.6          # верх ротонды

# ------------------------------------------------------------------ объёмы
def onF(p):
    """Точка фасада, спроектированная на прямую фасада (OSM гуляет на 2 м)."""
    v = F.o + F.u * U(p)
    return (v.x + RC[0], -v.y + RC[1])
FA, FB, FC = onF((369.2, 7108.6)), onF((375.6, 7124.9)), onF((380.0, 7138.0))
NORTH = [(279.0, 7072.2), (333.3, 7050.2), P_N, FA, FB, FC, (314.0, 7160.5), (308.0, 7146.5)]
SOUTH = [FC, P_S, (387.7, 7190.2), (333.3, 7210.4), (314.0, 7160.5)]
prism_world('wall', NORTH, GROUND, HW, roof='roof')
prism_world('wall', SOUTH, GROUND, HS, roof='roof')
for poly, h in ((NORTH, HW), (SOUTH, HS)):
    P = [W(x, z) for x, z in poly]
    for i in range(len(P)):
        a, b = P[i], P[(i + 1) % len(P)]
        beam('wall2', Vector((a.x, a.y, h + 0.35)), Vector((b.x, b.y, h + 0.35)), 0.3, 0.7)
# венткамеры на кровле (на спутнике — ряды коробов)
for (x, z) in ((300, 7090), (318, 7085), (335, 7080), (310, 7118), (330, 7112), (350, 7105),
               (330, 7150), (350, 7144), (345, 7180), (365, 7172)):
    hh = HW if z < 7140 else HS
    c = W(x, z)
    Fb = Frame(c, F.u, F.n)
    box('wall2', Fb, -1.6, 1.6, -1.2, 1.2, hh, hh + 1.4)

# ------------------------------------------------------------------ стеклянные крылья
def wing(u0, u1, h, d=0.06):
    curtain(F, u0, u1, 0.0, 4.4, d, du=3.0, dz=4.4)
    box('wall', F, u0, u1, 0, d + 0.25, 4.4, 4.95)
    curtain(F, u0, u1, 4.95, h - 2.2, d, du=1.6, dz=1.8)
    box('wall', F, u0, u1, 0, d + 0.2, h - 2.2, h)
    box('wall2', F, u0, u1, 0, d + 0.24, h - 2.24, h - 2.16)

uRa, uRb = uR - RC[2] - 0.3, uR + RC[2] + 0.3
wing(uS + 1.0, uRa, HW)                      # южное крыло
uN = U((346.2, 7054.4)) - NC[2] - 1.0
wing(uRb, uN, HW)                            # северное крыло

# южный корпус: синий низ, красная и синяя полосы, белый верх с ленточным окном
d = 0.06
box('blue', F, 0, uS, 0, d + 0.05, 0, 4.6)
for k in range(int(uS // 9)):
    curtain(F, 2 + k * 9, 7.5 + k * 9, 1.0, 3.6, d + 0.06, du=1.8, dz=2.6)
box('red', F, 0, uS, 0, d + 0.08, 4.6, 5.1)
box('white', F, 0, uS, 0, d + 0.05, 5.1, 5.3)
box('blue', F, 0, uS, 0, d + 0.08, 5.3, 5.7)
curtain(F, 1.5, uS - 1.5, 6.6, 8.2, d, du=1.6, dz=1.6)

# ------------------------------------------------------------------ ротонда
a0, a1 = ang_of(RC[:2], ARC_MAIN[0]), ang_of(RC[:2], ARC_MAIN[-1])
if (a1 - a0) % 360 > 180:            # дуга идёт наружу, через восток
    a0, a1 = a1, a0
if a1 < a0: a1 += 360
pad = 12
r = RC[2] + 0.4
drum(RC[:2], r, a0 - pad, a1 + pad, 4.9, HW, n=16, rows=[7.1, 9.3, 11.5])
drum(RC[:2], r, a1 + pad, a0 - pad + 360, HW, HR - 1.0, n=16, rows=[13.7])   # над кровлей — по кругу
drum(RC[:2], r, a0 - pad, a1 + pad, HW, HR - 1.0, n=10, rows=[13.7])
# первый этаж ротонды: стекло глубже, круглый козырёк на колоннах
drum(RC[:2], r - 2.0, a0 - pad, a1 + pad, 0.0, 4.4, n=12, rows=[3.2])
ring('wall', RC[:2], r - 2.2, r + 0.3, a0 - pad, a1 + pad, 4.4, 4.95, n=16)
ring('wall', RC[:2], 0.5, r + 0.25, 0, 360, HR - 1.0, HR, n=24)
disc_flat('roof', RC[:2], 0.6, HR - 0.01, n=8)
for k in range(5):
    a = math.radians(a0 + (a1 - a0) * (k + 0.5) / 5)
    C = W(*RC[:2])
    p = Vector((C.x + (r - 0.3) * math.cos(a), C.y + (r - 0.3) * math.sin(a), 0))
    lathe('wall2', p, [(0.35, 0), (0.35, 4.4)], 10, cap=False)
# силуэты людей на витраже — тёмные фигуры в два яруса
C = W(*RC[:2])
for k in range(9):
    a = math.radians(a0 + (a1 - a0) * (k + 0.5) / 9)
    for zz in (6.0 + (k % 2) * 0.6, 10.2 - (k % 3) * 0.4):
        rr = r + 0.03
        p = Vector((C.x + rr * math.cos(a), C.y + rr * math.sin(a)))
        t = Vector((-math.sin(a), math.cos(a)))
        Ff = Frame(p, t, Vector((math.cos(a), math.sin(a))))
        box('figure', Ff, -0.28, 0.28, 0, 0.05, zz, zz + 1.25)
        disc('figure', Ff, 0, zz + 1.5, 0.22, 0, depth=0.05, seg=8)

# вывеска SEA MALL на ферме над ротондой
FS = Frame(W(*RC[:2]) + F.n * (r - 1.0), F.u, F.n)
truss(FS, -9.5, 9.5, HR, HR + 3.8, -0.3, bays=7)
text('blue', FS, 'SEA', -4.9, HR + 0.5, 3.0, 0.0, depth=0.35, fnt='Arial Black.ttf', width=7.6)
text('red', FS, 'MALL', 4.4, HR + 0.5, 3.0, 0.0, depth=0.35, fnt='Arial Black.ttf', width=9.8)
# чайка-галочка над словами
prism_uz('white', FS, [(-1.4, HR + 3.7), (-0.4, HR + 2.3), (1.9, HR + 4.8), (-0.3, HR + 3.0)], 0.0, 0.3)

# ------------------------------------------------------------------ вывески арендаторов на фризе
ZF = HW - 2.0      # низ фриза
# южное крыло: SUNLIGHT (красный короб) и SPORTS CITY (чёрный)
mu = (uS + uRa) / 2
ww = (uRa - uS - 2.0) / 2 - 0.3              # два короба в ширину крыла
board(F, mu - ww - 0.3, mu - 0.3, ZF + 0.35, ZF + 1.75, 0.3, 'red', depth=0.2)
text('white', F, 'SUNLIGHT', mu - ww / 2 - 0.3, ZF + 0.67, 0.7, 0.5, depth=0.06, width=ww - 0.8)
board(F, mu + 0.3, mu + ww + 0.3, ZF + 0.35, ZF + 1.75, 0.3, 'dark', depth=0.2)
text('white', F, 'SPORTS', mu + 0.3 + ww * 0.36, ZF + 0.67, 0.7, 0.5, depth=0.06, width=ww * 0.56)
text('red', F, 'CITY', mu + 0.3 + ww * 0.8, ZF + 0.67, 0.7, 0.5, depth=0.06, width=ww * 0.3)
print('КРЫЛЬЯ', round(uS, 1), round(uRa, 1), round(uRb, 1), round(uN, 1), round(LEN, 1))
# северное крыло: «Фильмотека / кинотеатр» с бобиной и розовое kari
mn = (uRb + uN) / 2
text('grey', F, 'ФИЛЬМОТЕКА', mn - 4.0, ZF + 0.85, 0.85, 0.3, depth=0.12, width=11.0)
text('grey', F, 'КИНОТЕАТР', mn - 4.0, ZF + 0.25, 0.45, 0.3, depth=0.1, width=7.0)
Fr = Frame(F.o + F.u * (mn - 4.0) + F.n * 0.9, F.u, F.n)
lathe('dark', Fr.p(0, 0, 0) + UP * HW, [(0.9, 0), (0.9, 0.35), (0.75, 0.4), (0.75, 0.75), (0.9, 0.8), (0.9, 1.15)], 14)
text('pink', F, 'kari', mn + 9.0, ZF + 0.3, 1.6, 0.3, depth=0.15, width=5.0)
# южный корпус: «Эльдорадо» — красный короб с белыми буквами
board(F, uS - 30, uS - 12, 8.4, 9.7, 0.1, 'red', depth=0.25)
text('white', F, 'ЭЛЬДОРАДО', uS - 20.0, 8.68, 0.8, 0.35, depth=0.06, width=13.0)
board(F, uS - 29.6, uS - 27.8, 8.6, 9.5, 0.35, 'white', depth=0.05)

# ------------------------------------------------------------------ угловые барабаны
for c, h in ((SC, HS), (NC, HW)):
    drum(c[:2], c[2] + 0.2, 0, 360, 0.0, h - 1.2, n=14, rows=[4.4, 7.0, 9.5][:2 if h < 11 else 3])
    ring('wall', c[:2], 0.3, c[2] + 0.45, 0, 360, h - 1.2, h, n=14)
    disc_flat('roof', c[:2], c[2] + 0.3, h + 0.01, n=14)

# цоколь по фасаду
box('stone', F, 0, LEN, -0.4, 0.3, GROUND, 0.05)

finish('mall_seamall', __file__)
