# Памятник матросу Петру Кошке (бюст, Севастополь).
#
#   blender -b --python models/koshka/build.py -- [glb]
#
# По фото Викисклада (refs/r0): бронзовый бюст в матросской бескозырке на сужающемся красно-розовом
# гранитном столбе с плитой-надписью «Матрос Кошка Пётр Маркович, герой обороны Севастополя»,
# бронзовым гербом (скрещённые пушки в венке, «1854–1855») и пирамидой ядер; по сторонам два якоря
# с цепным ограждением на столбиках; ступенчатое основание.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = 1020.4, 1285.4
origin(X0, Z0)
set_rot(world_rot(-0.7, 0.7))
COL['wall3'] = ((0.15, 0.16, 0.14), 0.5)
COL['metal'] = ((0.10, 0.10, 0.09), 0.5)
COL['wall2'] = ((0.50, 0.28, 0.24), 0.45)     # красно-розовый гранит
COL['stone'] = ((0.56, 0.52, 0.48), 0.9)
B = 'wall3'; G = 'wall2'
F0 = FR()

box('stone', F0, -4.0, 4.0, -4.0, 4.0, -0.3, 0.02)
frustum('stone', F0, (-2.9, 2.9, -2.5, 2.5), (-2.5, 2.5, -2.1, 2.1), -0.1, 0.45)
frustum('stone', F0, (-1.9, 1.9, -1.55, 1.55), (-1.75, 1.75, -1.4, 1.4), 0.45, 0.95)
frustum(G, F0, (-0.85, 0.85, -0.8, 0.8), (-0.62, 0.62, -0.6, 0.6), 0.95, 3.7)                 # столб
box(G, F0, -0.70, 0.70, -0.65, 0.65, 3.7, 3.82)
box(G, F0, -0.82, 0.82, -0.72, 0.72, 3.82, 4.5)
box(G, F0, -0.58, 0.58, -0.52, 0.52, 4.5, 4.62)
# плита-надпись и герб
Fl = FR(0, 0, -90)
plate('metal', Fl, -0.55, 0.55, 0.81, 3.95, 4.4, lines=4, seed=21, pr=0.03)
prism_uz('metal', Fl, [(0.42 * math.cos(2 * math.pi * k / 14), 2.45 + 0.42 * math.sin(2 * math.pi * k / 14)) for k in range(14)], 0.70, 0.78)
for dy in (-1, 1):                                                                               # скрещённые пушки
    beam('metal', P(0.80, dy * 0.28, 2.1), P(0.80, -dy * 0.28, 2.8), 0.1)
# ядра: пирамида 3-2-1
for r_, y_, z_ in ((0.17, -0.34, 1.12), (0.17, 0.0, 1.12), (0.17, 0.34, 1.12), (0.17, -0.17, 1.44), (0.17, 0.17, 1.44), (0.17, 0.0, 1.76)):
    blob(B, Vector((1.0, y_, z_ - 0.55)), r_, r_, r_, seg=6, rings=3)
# бюст: бескозырка, матросская куртка
bust(B, 4.62, k=1.5, hat='cap', hair=False, epaulets=False)
# якоря по бокам
for sg in (-1, 1):
    anchor(B, (0.5, sg * 1.7, 0.45), h=1.9, rot=sg * 0.5, lean=0.5)
# столбики ограждения и цепи
posts = []
for i in range(-3, 4):
    posts.append((2.9, i * 1.1))
for i in range(-2, 3):
    posts.append((i * 1.2 + 0.0, -3.3)); posts.append((i * 1.2 + 0.0, 3.3))
for (x, y) in posts:
    lathe(B, P(x, y, 0.0), [(0.07, 0), (0.07, 0.8), (0.1, 0.85), (0.0, 0.9)], 6, cap=False)
for i in range(-3, 3):
    beam('metal', P(2.9, i * 1.1, 0.7), P(2.9, (i + 1) * 1.1, 0.7), 0.03)
done('koshka', __file__, 1020.4, 1285.4, 'Памятник матросу Петру Кошке')
