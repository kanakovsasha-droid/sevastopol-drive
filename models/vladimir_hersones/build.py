# Памятник святому равноапостольному князю Владимиру (запад Севастополя), по фото Викисклада (refs/).
#
#   blender -b --python models/vladimir_hersones/build.py -- [glb]
#
# Бронзовая фигура князя в тунике с поясом и мантии, в шапке; правая рука поднята ладонью вперёд, рядом огромный
# восьмиконечный... (прямой) крест; левая рука на большом овальном щите. Постамент — прямоугольный столб из розового
# гранита с надписью «Святому равноапостольному великому князю Киевскому Владимиру» на двух гранитных ступенях.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = -2599.3, 1109.5
origin(X0, Z0)
set_rot(world_rot(0.0, 1.0))
COL['wall3'] = ((0.20, 0.18, 0.15), 0.5)
COL['metal'] = ((0.14, 0.13, 0.11), 0.5)
COL['wall2'] = ((0.58, 0.34, 0.30), 0.45)      # розовый гранит
COL['stone'] = ((0.62, 0.60, 0.56), 0.8)       # светло-серый гранит ступеней
B = 'wall3'; G = 'wall2'
F0 = FR()

box('stone', F0, -2.6, 2.6, -2.6, 2.6, -0.3, 0.03)
box('stone', F0, -1.7, 1.7, -1.7, 1.7, 0.0, 0.55)
box('stone', F0, -1.4, 1.4, -1.4, 1.4, 0.55, 1.1)
box(G, F0, -0.95, 0.95, -0.95, 0.95, 1.1, 4.4)                                  # столб
plate('metal', FR(0, 0, -90), -0.6, 0.6, 0.97, 2.1, 3.2, lines=6, seed=41, pr=0.01)
box('wall3', F0, -1.12, 1.12, -1.12, 1.12, 4.4, 4.6)                              # бронзовая плита под фигурой
z0 = 4.6
fg = Fig(3.1, face=(1, 0, 0), bulk=1.2, seg=8)
person(B, fg, pel=(0.0, 0, z0 + 1.58), neck=(0.02, 0, z0 + 2.55), head=(0.04, 0, z0 + 2.85),
       shL=(0.0, 0.46, z0 + 2.38), shR=(0.0, -0.46, z0 + 2.38),
       haL=(0.28, 0.58, z0 + 1.45), haR=(0.18, -0.85, z0 + 3.1),
       hipL=(0, 0.17, z0 + 1.5), hipR=(0, -0.17, z0 + 1.5),
       anL=(0.05, 0.19, z0 + 0.14), anR=(0.0, -0.19, z0 + 0.14),
       polesA=((0.2, 0.4, -1), (0.3, -0.5, -0.3)), polesL=((1, 0, 0), (1, 0, 0)),
       head_kind='hair', torso_w=1.2, head_r=1.1, arm_r=1.15, leg_r=1.0)
# туника до колена с поясом, мантия за спиной
skirt(B, [(Vector((0.0, 0, z0 + 1.7)), 0.38, 0.32, None), (Vector((0.0, 0, z0 + 1.2)), 0.45, 0.40, lambda t: 1 + 0.05 * math.sin(5 * t)),
          (Vector((0.0, 0, z0 + 0.60)), 0.50, 0.46, lambda t: 1 + 0.07 * math.sin(6 * t))], seg=12)
skirt(B, [(Vector((-0.22, -0.1, z0 + 2.35)), 0.2, 0.55, None), (Vector((-0.32, -0.15, z0 + 1.2)), 0.22, 0.7, lambda t: 1 + 0.06 * math.sin(4 * t)),
          (Vector((-0.38, -0.2, z0 + 0.12)), 0.24, 0.78, None)], seg=12)
# шапка с меховой оторочкой
blob(B, Vector((0.04, 0, z0 + 3.0)), 0.3, 0.28, 0.14, seg=10, rings=4, bot=0.5)
# щит
blob(B, Vector((0.45, 0.75, z0 + 0.95)), 0.2, 0.55, 0.95, seg=10, rings=5)
# крест (прямой, с расширяющимися концами)
beam(B, P(0.1, -0.98, z0 + 0.1), P(0.1, -0.98, z0 + 4.6), 0.11, 0.07)
beam(B, P(0.1, -1.7, z0 + 3.85), P(0.1, -0.26, z0 + 3.85), 0.1, 0.07)
blob(B, Vector((0.1, -0.98, z0 + 4.75)), 0.07, 0.12, 0.18, seg=4, rings=2)
done('vladimir_hersones', __file__, -2599.3, 1109.5, 'Памятник святому князю Владимиру (запад города)')
