# Памятник Э. И. Тотлебену «Оборона Севастополя» на Историческом бульваре, Севастополь.
#
#   blender -b --python models/totleben/build.py -- [glb]
#
# Бронзовый генерал-адъютант Тотлебен (шинель, фуражка в руке) на восьмигранном гранитном постаменте; у подножия
# на бронзовой скале — защитники Севастополя (матросы и солдаты со штыками, рабочий с габионом). Ниже — длинное
# гранитное основание с надписью «1854 ОБОРОНА СЕВАСТОПОЛЯ 1855». Размеры — по фото Викисклада (refs/).
# Ноль высоты — площадка у основания. Лицом на юг (к панораме).
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = -157.6, 1988.0
origin(X0, Z0)
set_rot(world_rot(-0.16, 0.99))
COL['wall3'] = ((0.16, 0.20, 0.17), 0.5)      # тёмная бронза
COL['metal'] = ((0.10, 0.13, 0.11), 0.5)
COL['wall2'] = ((0.60, 0.59, 0.55), 0.7)      # светло-серый инкерманский камень/гранит
COL['stone'] = ((0.58, 0.55, 0.50), 0.9)
B = 'wall3'; G = 'wall2'
F0 = FR()

# ------------------------------------------------------------------ основание
box('stone', F0, -6.5, 6.5, -7.0, 7.0, -0.4, 0.02)
frustum(G, F0, (-2.9, 2.9, -4.9, 4.9), (-2.5, 2.5, -4.5, 4.5), -0.2, 1.1)         # нижняя ступень
box(G, F0, -2.5, 2.5, -4.5, 4.5, 1.1, 1.7)
for sy in (-1, 1):                                                                 # угловые тумбы
    u0, u1 = sorted((sy * 3.55, sy * 4.6))
    box(G, F0, -2.5, 2.9, u0, u1, 0.9, 2.3)
    box(G, F0, -2.5, 3.0, u0 - 0.05, u1 + 0.05, 2.3, 2.45)
# надпись на лицевой стороне: даты на тумбах, название посередине
Fp = FR(0, 0, -90)             # смотрит вперёд (+x): u — вдоль −y, n — вперёд
plate('metal', Fp, 3.65, 4.5, 2.95, 0.95, 1.75, lines=1, seed=1, pr=0.02)
plate('metal', Fp, -4.5, -3.65, 2.95, 0.95, 1.75, lines=1, seed=2, pr=0.02)
plate('metal', Fp, -1.9, 1.9, 2.6, 0.85, 1.35, lines=1, seed=3, pr=0.02)
frustum(G, F0, (-2.2, 2.2, -2.7, 2.7), (-1.9, 1.9, -2.3, 2.3), 1.7, 2.6)           # верхняя ступень

# ------------------------------------------------------------------ восьмигранный постамент
octa(G, F0, 0, 0, 1.85, 2.6, 2.95, taper=0.92)
octa(G, F0, 0, 0, 1.55, 2.95, 6.7, taper=0.92)
octa(G, F0, 0, 0, 1.62, 6.7, 6.9, taper=1.0)
octa(G, F0, 0, 0, 1.78, 6.9, 7.25, taper=1.0)
plate('metal', Fp, -0.7, 0.7, 1.45, 5.1, 5.75, lines=1, seed=5, pr=0.02)            # «ТОТЛЕБЕНЪ»

# ------------------------------------------------------------------ скала и защитники
rock = [((0.7, -1.9, 3.0), 1.1, 0.9, 0.7), ((0.9, 0.3, 3.1), 1.5, 1.1, 0.8), ((0.8, 2.0, 3.0), 1.1, 0.9, 0.7),
        ((0.2, -2.4, 3.3), 0.7, 0.7, 0.6), ((0.1, 2.5, 3.2), 0.7, 0.7, 0.6), ((1.4, -0.7, 3.4), 0.8, 0.6, 0.5),
        ((1.5, 1.2, 3.3), 0.8, 0.7, 0.5), ((-0.4, 0.0, 3.0), 1.2, 2.2, 0.8)]
for c, rx, ry, rz in rock:
    blob(B, Vector(c), rx, ry, rz, seg=8, rings=4)
for c in ((1.7, -1.8, 3.9), (1.3, 2.1, 3.9)):                                          # габионы-корзины
    lathe(B, P(*c), [(0.33, 0.0), (0.3, 0.3), (0.34, 0.55), (0.0, 0.55)], 8, cap=False)

def rifle(T, a, b):
    tube(B, [T(*a), T(*b)], [0.035, 0.035], 5)
    d = (T(*b) - T(*a)).normalized()
    tube(B, [T(*b), T(*b) + d * 0.55], [0.025, 0.003], 4)

def stand(cx, cy, zb, ang, kind, lean=0.0, step=0.32, arms=None, rf=None):
    a = math.radians(ang); ca, sa = math.cos(a), math.sin(a)
    T = lambda x, y, z: Vector((cx + x * ca - y * sa, cy + x * sa + y * ca, zb + z))
    R = lambda x, y, z: T(x, y, z) - T(0, 0, 0)
    Hh = 1.85
    fgs = Fig(Hh, face=(ca, sa, 0), bulk=1.05, seg=6)
    lx = lean
    pel = T(-0.05 + lx * 0.2, 0, 0.95); neck = T(0.08 + lx * 0.7, 0, 1.55); head = T(0.12 + lx * 0.85, 0, 1.72)
    arms = arms or ((0.45, -0.28, 1.15), (0.4, 0.28, 1.15))
    hk = {'sailor': 'cap', 'soldier': 'cap', 'worker': 'hair'}[kind]
    person(B, fgs, pel=pel, neck=neck, head=head,
           shL=T(0.06 + lx * 0.6, 0.26, 1.45), shR=T(0.06 + lx * 0.6, -0.26, 1.45),
           haL=T(*arms[1]), haR=T(*arms[0]),
           hipL=T(-0.05, 0.11, 0.9), hipR=T(-0.05, -0.11, 0.9),
           anL=T(step, 0.13, 0.1), anR=T(-step, -0.13, 0.1),
           polesA=(R(0, 0.3, -1), R(0, -0.3, -1)), polesL=(R(1, 0, 0.3), R(1, 0, 0.2)),
           toe=(T(2, 0.13, 0.1), T(2, -0.13, 0.1)), head_kind=hk, torso_w=1.15, head_r=1.0, arm_r=1.1, leg_r=1.1)
    if rf:
        rifle(T, rf[0], rf[1])
    return T

# слева от зрителя (−y): матрос с шанцевым инструментом, солдат со штыком; справа: матрос, рабочий с габионом
stand(1.0, -2.0, 3.55, 20, 'sailor', lean=0.1, arms=((0.35, -0.2, 1.25), (0.45, 0.3, 1.0)), rf=((0.1, -0.2, 0.2), (0.55, -0.2, 1.4)))
stand(1.6, -0.8, 3.65, 5, 'soldier', lean=0.12, step=0.36, arms=((0.55, -0.15, 1.2), (0.3, 0.3, 1.1)), rf=((0.0, -0.2, 0.55), (1.1, -0.1, 1.95)))
stand(1.6, 0.8, 3.65, -8, 'sailor', lean=0.18, step=0.4, arms=((0.6, -0.2, 1.25), (0.35, 0.3, 1.0)), rf=((-0.1, 0.25, 0.7), (1.2, -0.15, 1.75)))
stand(0.8, 2.2, 3.7, -25, 'worker', lean=0.05, arms=((0.45, -0.25, 1.1), (0.5, 0.3, 1.0)))
stand(0.0, 2.6, 3.4, -50, 'soldier', lean=0.2, step=0.2, arms=((0.4, -0.25, 1.0), (0.4, 0.25, 1.0)))

# ------------------------------------------------------------------ Тотлебен
zT = 7.25 + 0.25
blob(B, Vector((0, 0, 7.25)), 1.3, 1.3, 0.28, seg=10, rings=3, bot=0.3)
fg = Fig(3.15, face=(1, 0, 0), bulk=1.1, seg=8)
person(B, fg, pel=(0.0, 0, zT + 1.55), neck=(0.05, 0, zT + 2.62), head=(0.08, 0, zT + 2.93),
       shL=(0.0, 0.46, zT + 2.48), shR=(0.0, -0.46, zT + 2.48),
       haL=(0.12, 0.60, zT + 1.45), haR=(0.30, -0.22, zT + 2.1),
       hipL=(0, 0.16, zT + 1.45), hipR=(0, -0.16, zT + 1.45),
       anL=(0.04, 0.18, zT + 0.15), anR=(-0.02, -0.18, zT + 0.15),
       polesA=((0, 0.2, -1), (-0.3, -1, 0.1)), polesL=((1, 0, 0.1), (1, 0, 0.1)),
       head_kind='cap', torso_w=1.25, head_r=1.0, arm_r=1.15, leg_r=0.9)
# шинель: длинные полы до голенища
skirt(B, [(Vector((0.0, 0, zT + 1.65)), 0.36, 0.30, None),
          (Vector((0.0, 0, zT + 1.1)), 0.42, 0.38, lambda t: 1 + 0.04 * math.sin(5 * t)),
          (Vector((0.0, 0, zT + 0.55)), 0.50, 0.44, lambda t: 1 + 0.07 * math.sin(6 * t + 0.4)),
          (Vector((0.0, 0, zT + 0.45)), 0.52, 0.46, None)], seg=12)
# ремень, фуражка в левой руке
blob(B, Vector((0.14, 0.64, zT + 1.28)), 0.2, 0.2, 0.06, seg=8, rings=3)
done('totleben', __file__, -157.6, 1988.0, 'Памятник Э. И. Тотлебену «Оборона Севастополя»')
