# Памятник А. И. Казарскому на Матросском бульваре (1834–1839, арх. А. П. Брюллов).
#
#   blender -b --python models/kazarsky/build.py -- [glb]
#
# Две ступени цоколя из инкерманского камня, высокая усечённая пирамида с надписью
# «Казарскому. Потомству в пример» и чугунными фасциями (мечи/топор), куб с чугунными пучками
# и барельефами, наверху — чугунная античная трирема с завитками на носу и корме и вёслами.
# Ноль высоты — площадка вокруг памятника.
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'mon_common'))
from mon import *

X0, Z0 = -101.6, 81.1
origin(X0, Z0)
FACING = -80          # надпись «Потомству в пример» смотрит на В (80°), в сторону площади Нахимова

COL['stone'] = ((0.66, 0.62, 0.53), 0.9)       # плиты площадки и нижняя ступень
COL['wall'] = ((0.80, 0.75, 0.62), 0.9)        # инкерманский известняк пирамиды
COL['wall2'] = ((0.77, 0.72, 0.60), 0.9)       # куб
COL['wall3'] = ((0.10, 0.105, 0.10), 0.5)      # чугун (трирема, фасции)
COL['metal'] = ((0.10, 0.105, 0.10), 0.5)
COL['trim'] = ((0.42, 0.33, 0.17), 0.45)       # позолота/бронза по борту

B, M = 'wall3_s', 'metal_s'
GR = -0.5

def courses(m, z0, z1, hx0, hy0, hx1, hy1, step, off=0.012):
    """Кладка: слои с чуть разным вылетом — тени швов на усечённой пирамиде."""
    n = max(1, round((z1 - z0) / step))
    for i in range(n):
        ta, tb = i / n, (i + 1) / n
        a = (hx0 + (hx1 - hx0) * ta, hy0 + (hy1 - hy0) * ta)
        b = (hx0 + (hx1 - hx0) * tb, hy0 + (hy1 - hy0) * tb)
        e = off if i % 2 == 0 else 0.0
        rloft(m, [(z0 + (z1 - z0) * ta, a[0] + e, a[1] + e), (z0 + (z1 - z0) * tb, b[0] + e, b[1] + e)], 0, 0, top=(i == n - 1))

def build_base():
    slab('stone', -2.3, 2.3, -2.3, 2.3, GR, 0.14)
    slab('stone', -1.95, 1.95, -1.95, 1.95, 0.14, 0.34)
    slab('wall', -1.72, 1.72, -1.72, 1.72, 0.34, 0.9)
    slab('wall2', -1.62, 1.62, -1.62, 1.62, 0.9, 0.98)

def build_pyramid():
    z0, z1 = 0.98, 3.78
    courses('wall', z0, z1, 1.52, 1.52, 0.93, 0.93, 0.4)
    # венчающий карниз пирамиды
    rloft('wall2', [(z1, 1.0, 1.0), (z1 + 0.1, 1.04, 1.04), (z1 + 0.2, 0.98, 0.98)], 0, 0)
    # передняя грань (+Y): надпись чугунными буквами, фасции (3 меча в венках и топор), как на фото
    yF = lambda z: 0.93 + (1.52 - 0.93) * (z1 - z) / (z1 - z0)        # глубина грани на высоте z
    F = Frame(Vector((0, 0)), Vector((1, 0)), Vector((0, 1)))
    for k, u in enumerate((-0.68, -0.34, 0.0, 0.34, 0.68)):
        zt, zb = 3.55, 2.62
        d = yF((zt + zb) / 2) + 0.03
        if k == 2:        # секира с двумя лезвиями
            limb(M, V(u, d, zt), V(u, d, zb), 0.028, 0.02, 6)
            strip(M, V(u - 0.12, d + 0.005, zt - 0.07), V(u + 0.12, d + 0.005, zt - 0.07), 0.16, 0.16, 0.025, Vector((0, 1, 0)))
            strip(M, V(u, d + 0.005, zt - 0.2), V(u, d + 0.005, zt + 0.08), 0.1, 0.0001, 0.02, Vector((1, 0, 0)))
        else:             # меч в венке
            limb(M, V(u, d, zt - 0.1), V(u, d, zb), 0.03, 0.012, 6)
            loft(M, [(u, d + 0.01, zt - 0.28, 0.085, 0.03), (u, d + 0.01, zt - 0.2, 0.085, 0.03)], 12, cap0=False, cap1=False)
            ellipsoid(M, V(u, d + 0.02, zt - 0.24), 0.1, 0.045, 0.1, 8, 4)           # венок
            slab(M, u - 0.025, u + 0.025, d - 0.01, d + 0.04, zt - 0.1, zt + 0.03)    # рукоять
    # надпись: три строки + «В» — выпуклые полосы
    for zz, ww in ((2.28, 1.2), (1.98, 1.35), (1.76, 0.2), (1.52, 0.8)):
        d = yF(zz) + 0.02
        slab(M, -ww / 2, ww / 2, d, d + 0.03, zz, zz + 0.1)
    # боковые грани: «Казарскому 1834», маска льва и скрещённые пистолеты на правой/левой
    for sx in (-1, 1):
        d = yF(1.7) + 0.02
        Fs = Frame(Vector((0, 0)), Vector((0, sx)), Vector((sx, 0)))   # u вдоль грани, n наружу
        slab_ = lambda u0, u1, d0, d1, z0_, z1_: box(M, Fs, u0, u1, d0, d1, z0_, z1_)
        slab_(-0.45, 0.45, yF(2.28) + 0.02, yF(2.28) + 0.05, 2.28, 2.36)
        slab_(-0.2, 0.2, yF(2.0) + 0.02, yF(2.0) + 0.05, 2.0, 2.08)
        ellipsoid(M, Fs.p(0, yF(1.6) + 0.06, 1.62), 0.1, 0.06, 0.11, 8, 4)           # маска льва
    # задняя грань — то же без украшений

def build_cube():
    z0 = 3.98
    # плинт под кубом и куб
    slab('wall2', -0.82, 0.82, -0.82, 0.82, z0 - 0.08, z0 + 0.0)
    slab('wall2', -0.72, 0.72, -0.72, 0.72, z0, z0 + 0.85)
    slab('wall2', -0.79, 0.79, -0.79, 0.79, z0 + 0.85, z0 + 0.92)
    # барельефы: чугунная плита с фигурами-силуэтами на каждой грани
    for k in range(4):
        a = k * math.pi / 2
        F = Frame(Vector((0, 0)), Vector((math.cos(a), math.sin(a))), Vector((-math.sin(a), math.cos(a))))
        box(M, F, -0.34, 0.34, 0.70, 0.76, z0 + 0.14, z0 + 0.72)
        for u, h, r in ((-0.13, 0.30, 0.04), (0.05, 0.38, 0.045), (0.2, 0.22, 0.04)):
            box(M, F, u - 0.045, u + 0.045, 0.76, 0.80, z0 + 0.2, z0 + 0.2 + h)
            ellipsoid(M, F.p(u, 0.78, z0 + 0.2 + h + 0.04), r, 0.03, r, 6, 3)
        # пучки фасций по углам (чугун): колонка из трёх стержней и секира сверху
        for sgn in (-1, 1):
            cu = sgn * 0.72
            for j in (-1, 0, 1):
                limb(M, F.p(cu + j * 0.05, 0.62, z0 - 0.0), F.p(cu + j * 0.05, 0.62, z0 + 0.92), 0.028, 0.028, 6)
            limb(M, F.p(cu, 0.64, z0 + 0.35), F.p(cu, 0.64, z0 + 0.4), 0.075, 0.075, 8)
            strip(M, F.p(cu, 0.62, z0 + 0.88), F.p(cu, 0.62, z0 + 1.1), 0.22, 0.02, 0.03, Vector((0, 1, 0)))
    # тёмная вставка-пояс под кораблём
    slab(M, -0.82, 0.82, -0.82, 0.82, z0 + 0.92, z0 + 0.97)

def build_trireme():
    zb = 4.95
    # корпус: ладья-раструб — в плане «лодка» с заострёнными концами, снизу узкий, кверху расширяется
    def ring(z, L, Bw, sag=0.0):
        pts = []
        n = 24
        for k in range(n):
            t = 2 * math.pi * k / n
            c, s = math.cos(t), math.sin(t)
            x = L * c
            # заострение носа и кормы
            y = Bw * s * (1 - 0.65 * abs(c) ** 2.2)
            pts.append(V(x, y, z + sag * (abs(c) ** 3)))
        return pts
    rings = [ring(zb, 0.62, 0.28), ring(zb + 0.1, 0.75, 0.36), ring(zb + 0.28, 1.0, 0.55, 0.12),
             ring(zb + 0.44, 1.25, 0.82, 0.2), ring(zb + 0.54, 1.3, 0.88, 0.25), ring(zb + 0.6, 1.2, 0.80, 0.25)]
    skin(B, rings, cap0=True, cap1=False)
    # палуба с леерным ограждением (кормовая часть) и золочёный пояс по борту
    deck = ring(zb + 0.6, 1.2, 0.80, 0.25)
    skin('trim', [ring(zb + 0.5, 1.27, 0.865, 0.24), ring(zb + 0.58, 1.31, 0.89, 0.255)], cap0=False, cap1=False)
    # завитки: на корме (−X) большой, на носу (+X) с тараном
    ex, ey = V(1, 0, 0), V(0, 0, 1)
    spiral(B, V(-1.18, 0.0, zb + 0.95), (ex, ey), 0.34, 0.06, math.pi * 0.2, math.pi * 2.9, 16, 0.07, 0.04)
    limb(B, V(-1.2, 0.0, zb + 0.6), V(-1.18, 0.0, zb + 0.9), 0.1, 0.07, 6)
    ellipsoid(B, V(-1.18, 0.0, zb + 0.95), 0.12, 0.09, 0.12, 8, 4)
    spiral(B, V(1.15, 0.0, zb + 0.82), (ex, ey), 0.30, 0.05, math.pi * 0.9, -math.pi * 1.7, 16, 0.065, 0.04)
    limb(B, V(1.18, 0.0, zb + 0.6), V(1.2, 0.0, zb + 0.8), 0.09, 0.06, 6)
    # таран и носовая штевень
    limb(B, V(1.1, 0.0, zb + 0.3), V(1.5, 0.0, zb + 0.28), 0.06, 0.03, 6)
    
    # ограждение кормы: перила с решёткой
    for sy in (-1, 1):
        for i in range(8):
            x = -1.0 + 0.13 * i
            limb(M, V(x, sy * 0.56, zb + 0.7), V(x, sy * 0.56, zb + 0.9), 0.012, 0.012, 4)
        limb(M, V(-1.0, sy * 0.56, zb + 0.9), V(0.0, sy * 0.56, zb + 0.9), 0.018, 0.018, 4)
    # вёсла: ряд по каждому борту, веерно вниз-наружу
    for sy in (-1, 1):
        for i in range(8):
            x = -0.95 + 0.27 * i
            w = 0.82 - 0.3 * abs(x / 1.1) ** 2
            strip(B, V(x, sy * (w - 0.04), zb + 0.5), V(x + 0.1, sy * (w + 0.2), zb + 0.22), 0.05, 0.09, 0.022, Vector((1, 0, 0)))
    # розетки по борту (золочёные)
    for sy in (-1, 1):
        for i in range(9):
            x = -1.0 + 0.25 * i
            ellipsoid('trim', V(x, sy * (0.80 - 0.34 * (abs(x) / 1.1) ** 2 + 0.07), zb + 0.4), 0.035, 0.02, 0.035, 5, 2)

def build():
    build_base()
    build_pyramid()
    build_cube()
    build_trireme()
    rot_all(FACING)

build()
finish('kazarsky', __file__, 12000)
