# Памятник адмиралу П. С. Нахимову на площади Нахимова — модель с нуля.
#
#   blender -b --python models/nahimov_monument/build.py -- [glb]
#
# Ступенчатый гранитный стилобат, четыре «щёки» с якорями, цоколь, расширяющийся нижний
# постамент с бронзовыми барельефами, верхний постамент усечённой пирамидой с надписью и
# бронзовым развёрнутым флагом, фигура адмирала в шинели с подзорной трубой/свитком.
# Размеры сняты по фото (refs/), см. NOTES.md. Ноль высоты — плита площади.
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'mon_common'))
from mon import *

X0, Z0 = -5.8, 1.7                 # центр постамента (по спутнику и панораме)
origin(X0, Z0)
FACING_DEG = 25                    # фасад смотрит на 335° (СЗ), повёрнут от севера на 25° против часовой

COL['stone'] = ((0.40, 0.38, 0.35), 0.85)       # серый гранит (плита, ступени)
COL['wall'] = ((0.43, 0.36, 0.29), 0.8)         # коричнево-охристый гранит нижнего постамента
COL['wall2'] = ((0.31, 0.31, 0.32), 0.7)        # тёмно-серый гранит верхнего постамента
COL['wall3'] = ((0.12, 0.13, 0.115), 0.5)       # тёмная бронза с зеленцой
COL['metal'] = ((0.12, 0.13, 0.115), 0.5)
COL['trim'] = ((0.52, 0.50, 0.46), 0.8)         # полированные пояски

B = 'wall3_s'      # бронза (видна и издалека)
M = 'metal_s'      # бронза, мелочь

# ---------------------------------------------------------------- размеры, м (оценка по фото)
Z_PLAT = 0.30      # плита
Z_ST1, Z_ST2 = 0.65, 1.00          # верх ступеней
Z_CHEEK = 1.30     # щёки со якорями
Z_BASE = 1.75      # верх цоколя
Z_FLARE = 3.55     # верх расширяющегося постамента (под карнизом)
Z_COR = 4.05       # верх карниза
Z_UP = 8.55        # верх верхнего постамента
Z_FIG = 8.90       # подошва фигуры (плинт)
GROUND = -0.6

def build_base():
    # плита-стилобат: 11 × 8.6, фасад к +Y
    slab("stone", -5.2, 5.2, -4.3, 4.6, GROUND, Z_PLAT)
    # две ступени по центру
    slab('stone', -2.15, 2.15, 2.55, 3.4, GROUND, Z_ST1)
    slab('stone', -2.15, 2.15, 2.0, 2.55, GROUND, Z_ST2)
    # щёки со ступенями: блоки по бокам лестницы, поверх — якоря
    for s in (-1, 1):
        x0, x1 = sorted((s * 2.2, s * 4.3))
        slab('stone', x0, x1, -1.9, 3.4, GROUND, Z_CHEEK - 0.1)
        slab('trim', x0 - 0.05, x1 + 0.05, -1.95, 3.45, Z_CHEEK - 0.1, Z_CHEEK)
        anchor(M, V((x0 + x1) / 2, 1.3, Z_CHEEK), math.radians(18 * s), 1.05)
        # цепь-ожерелье: несколько звеньев вдоль блока
        for k in range(6):
            lx = (x0 + x1) / 2 + s * 0.15 * (k % 2)
            slab(M, lx - 0.06, lx + 0.06, -0.9 + k * 0.28, -0.9 + k * 0.28 + 0.2, Z_CHEEK, Z_CHEEK + 0.07)
    # цоколь двумя ярусами
    rloft('stone', [(GROUND, 3.1, 2.85), (Z_BASE - 0.65, 3.1, 2.85)], 0, 0, top=False)
    rloft('trim', [(Z_BASE - 0.65, 3.15, 2.9), (Z_BASE - 0.5, 3.15, 2.9)], 0, 0, top=False)
    rloft('stone', [(Z_BASE - 0.5, 2.9, 2.65), (Z_BASE - 0.12, 2.82, 2.57)], 0, 0, top=False)
    rloft('trim', [(Z_BASE - 0.12, 2.85, 2.6), (Z_BASE, 2.85, 2.6)], 0, 0)

def build_pedestal():
    # нижний постамент: вогнутый «раструб» от 2.5×2.3 к 2.0×1.75
    prof = []
    n = 8
    for i in range(n + 1):
        t = i / n
        k = (1 - t) ** 4
        z = Z_BASE + (Z_FLARE - Z_BASE) * t
        prof.append((z, 1.95 + 0.55 * k * 1.1 - 0.0, 1.70 + 0.55 * k * 1.1))
    prof[0] = (prof[0][0], 2.45, 2.20)
    rloft('wall', prof, 0, 0, top=False)
    # карниз
    rloft('trim', [(Z_FLARE, 1.92, 1.67), (Z_FLARE + 0.12, 2.12, 1.87)], 0, 0, top=False)
    rloft('trim', [(Z_FLARE + 0.12, 2.12, 1.87), (Z_FLARE + 0.22, 2.12, 1.87)], 0, 0, top=False)
    rloft('trim', [(Z_FLARE + 0.22, 2.0, 1.75), (Z_COR, 2.0, 1.75)], 0, 0)
    # барельефы: на фасаде (+Y) и на левой стороне (-X, от зрителя); бронзовый фон + фигуры
    def relief(face_axis, side_sign, width, h0, h1, nfig, seed):
        # локальная рамка на грани постамента: u вдоль грани, d наружу
        F = Frame(V(0, 0, 0).xy, Vector((1, 0)), Vector((0, 1)))
        if face_axis == 'front':
            F = Frame(Vector((0, 0)), Vector((1, 0)), Vector((0, 1)))
            d0 = 1.72
        else:
            F = Frame(Vector((0, 0)), Vector((0, side_sign * -1)), Vector((side_sign, 0)))
            d0 = 1.97
        # вогнутая плита: на фасаде постамент почти вертикален между z=2.15 и 3.1
        zf0, zf1 = h0, h1
        # положение грани по высоте (раструб) — берём глубину d на середине
        dd = d0
        box(M, F, -width / 2, width / 2, dd - 0.1, dd + 0.1, zf0, zf1)
        random_state = seed
        for i in range(nfig):
            u = -width / 2 + 0.2 + (width - 0.4) * i / max(1, nfig - 1)
            hgt = 0.80 + 0.14 * ((i * 7 + seed) % 3) / 2
            zb = zf0 + 0.08
            wd = 0.17
            box(M, F, u - wd, u + wd, dd + 0.1, dd + 0.2, zb, zb + hgt * 0.72)       # туловище
            box(M, F, u - wd * 0.8, u - wd * 0.1, dd + 0.1, dd + 0.18, zb + hgt * 0.72, zb + hgt * 0.78)
            ellipsoid(M, F.p(u, dd + 0.16, zb + hgt * 0.86), 0.075, 0.07, 0.09, 6, 3)   # голова
            if i % 3 == 0:
                box(M, F, u + wd, u + wd + 0.22, dd + 0.1, dd + 0.16, zb + hgt * 0.5, zb + hgt * 0.56)  # рука
        # ядра у пушек
        for i in range(6):
            ellipsoid(M, F.p(-width / 2 + 0.55 + (i % 3) * 0.1, dd + 0.08, zf0 + 0.06 + 0.1 * (i // 3)), 0.055, 0.055, 0.055, 6, 3)
    relief('front', 1, 3.1, 2.4, 3.35, 11, 1)
    relief('left', -1, 3.1, 2.4, 3.35, 11, 2)
    # верхний постамент: усечённая пирамида, внизу пояс-карниз
    rloft('wall2', [(Z_COR, 1.62, 1.50), (Z_COR + 0.25, 1.62, 1.50)], 0, 0, top=False)
    rloft('trim', [(Z_COR + 0.25, 1.70, 1.58), (Z_COR + 0.45, 1.70, 1.58)], 0, 0, top=False)
    rloft('wall2', [(Z_COR + 0.45, 1.52, 1.40), (Z_UP - 0.3, 1.02, 0.96)], 0, 0, top=False)
    rloft('trim', [(Z_UP - 0.3, 1.12, 1.06), (Z_UP, 1.12, 1.06)], 0, 0)
    # плинт под фигурой, тёмная бронза
    rloft(B, [(Z_UP, 1.0, 0.92), (Z_FIG, 1.0, 0.92)], 0, 0)
    # надпись «АДМИРАЛУ ПАВЛУ СТЕПАНОВИЧУ НАХИМОВУ» — три строки выпуклых полос
    yF = 1.4 - (1.4 - 0.96) * ((6.6 - (Z_COR + 0.45)) / (Z_UP - 0.3 - Z_COR - 0.45))
    F = Frame(Vector((0, 0)), Vector((1, 0)), Vector((0, 1)))
    for zz, ww, hh in ((7.55, 0.7, 0.07), (7.38, 1.2, 0.09), (7.12, 1.5, 0.15)):
        box(M, F, -ww / 2, ww / 2, 1.04, 1.07, zz, zz + hh)
    # развёрнутый флаг, вьющийся по передней грани: диагональное древко и ткань
    p0, p1 = V(1.15, 1.37, Z_COR + 0.5), V(-0.55, 1.12, Z_COR + 2.7)
    limb(M, p0, p1, 0.04, 0.04, 6)
    # ткань: сетка складок, свисает вправо-вниз от древка
    cols = 7
    rows = 6
    verts = []
    for r in range(rows + 1):
        rowv = []
        for c in range(cols + 1):
            tu = c / cols      # вдоль древка
            tv = r / rows      # вниз от древка
            base = p0 + (p1 - p0) * tu
            x = base.x - 0.15 - 0.8 * tv * (1 - 0.3 * tu) - 0.06 * math.sin(c * 1.7)
            z = base.z - 2.6 * tv * (0.75 + 0.25 * math.sin(c * 1.3 + 0.5)) * (1 - 0.35 * tu) - 0.25 * tv
            z = max(z, Z_COR + 0.38)
            y = 1.40 - 0.38 * tu + 0.22 * math.sin(c * 2.3 + r * 0.6) * (0.3 + tv) + 0.12
            # не уходить в грань постамента: глубина грани в этой точке
            zface = z
            yface = 1.45 - (1.45 - 0.96) * ((z - (Z_COR + 0.45)) / (Z_UP - 0.3 - Z_COR - 0.45))
            y = max(y, yface + 0.05)
            rowv.append(Vector((x, y, z)))
        verts.append(rowv)
    bm = bm_of(M)
    for r in range(rows):
        for c in range(cols):
            vs = [bm.verts.new(verts[r][c]), bm.verts.new(verts[r][c + 1]),
                  bm.verts.new(verts[r + 1][c + 1]), bm.verts.new(verts[r + 1][c])]
            f = bm.faces.new(vs); f.smooth = True
    # доска с текстом слева под флагом
    slab(M, 0.85, 1.45, 1.52, 1.58, Z_COR + 0.05, Z_COR + 0.55)

def build_figure():
    z0 = Z_FIG
    # ноги в брюках, сапоги; чуть расставлены
    for s in (-1, 1):
        limb(B, V(s * 0.20, 0.03, z0 + 0.25), V(s * 0.22, 0.0, z0 + 1.45), 0.125, 0.16, 10)
        ellipsoid(B, V(s * 0.21, 0.14, z0 + 0.13), 0.13, 0.30, 0.13, 10, 5)
    # шинель до колен: подол колоколом с лёгкими складками, талия, широкая грудь, покатые плечи
    secs = [
        (0, 0.0, z0 + 1.22, 0.58, 0.36, 0.0, 0.06, 7),
        (0, 0.0, z0 + 1.45, 0.56, 0.34, 0.0, 0.045, 7),
        (0, 0.0, z0 + 2.0, 0.50, 0.30, 0.0, 0.02, 7),
        (0, 0.0, z0 + 2.55, 0.46, 0.275),
        (0, 0.0, z0 + 3.0, 0.52, 0.30),
        (0, 0.0, z0 + 3.45, 0.60, 0.325),
        (0, 0.0, z0 + 3.78, 0.64, 0.30),
        (0, 0.0, z0 + 3.93, 0.50, 0.25),
        (0, 0.0, z0 + 4.02, 0.22, 0.19),
    ]
    loft(B, secs, 22)
    # борт шинели: две продольные накладки (двубортный, застёжка в два ряда) и отвороты
    for s in (-1, 1):
        limb(M, V(s * 0.04, 0.33, z0 + 1.28), V(s * 0.17, 0.315, z0 + 3.4), 0.018, 0.018, 4)
    for s in (-1, 1):
        strip(M, V(s * 0.12, 0.30, z0 + 3.42), V(s * 0.30, 0.25, z0 + 3.88), 0.12, 0.09, 0.03, Vector((0, 1, 0)))
    # воротник-стойка
    loft(B, [(0, 0, z0 + 3.92, 0.24, 0.205), (0, 0, z0 + 4.14, 0.225, 0.19)], 16, cap0=False, cap1=False)
    # голова: лицо, бакенбарды, усы
    ellipsoid(B, V(0, 0.02, z0 + 4.33), 0.20, 0.22, 0.27, 14, 7)
    ellipsoid(B, V(0, 0.19, z0 + 4.27), 0.045, 0.06, 0.06, 6, 3)                     # нос
    for s in (-1, 1):
        ellipsoid(B, V(s * 0.17, 0.0, z0 + 4.22), 0.055, 0.1, 0.13, 6, 3)             # бакенбарды
        ellipsoid(B, V(s * 0.05, 0.19, z0 + 4.13), 0.07, 0.04, 0.025, 6, 3)           # усы
        ellipsoid(B, V(s * 0.085, 0.17, z0 + 4.36), 0.06, 0.04, 0.025, 6, 3)          # надбровья
    # фуражка: околыш, чуть шире плоская тулья, козырёк
    loft(B, [(0, -0.01, z0 + 4.52, 0.235, 0.255), (0, -0.01, z0 + 4.66, 0.24, 0.26),
             (0, -0.01, z0 + 4.72, 0.28, 0.30), (0, -0.01, z0 + 4.82, 0.285, 0.30)], 20)
    loft(M, [(0, -0.01, z0 + 4.60, 0.245, 0.265), (0, -0.01, z0 + 4.64, 0.246, 0.266)], 20, cap0=False, cap1=False)
    strip(M, V(0, 0.23, z0 + 4.55), V(0, 0.46, z0 + 4.50), 0.34, 0.30, 0.025, Vector((0, 1, 0)))
    # эполеты: широкие, спускаются по плечу, с бахромой
    for s in (-1, 1):
        strip(M, V(s * 0.50, 0.0, z0 + 3.98), V(s * 0.78, 0.0, z0 + 3.72), 0.20, 0.17, 0.05, Vector((0, 1, 0)))
        limb(M, V(s * 0.76, 0.0, z0 + 3.76), V(s * 0.80, 0.0, z0 + 3.62), 0.095, 0.085, 8)   # бахрома
        ellipsoid(M, V(s * 0.50, 0.0, z0 + 3.98), 0.07, 0.1, 0.04, 6, 3)
    # правая рука (+X): рукав к локтю вдоль тела, предплечье вперёд, в кулаке свёрнутый чертёж
    sh, el, hd = V(0.66, 0.0, z0 + 3.72), V(0.74, -0.03, z0 + 2.78), V(0.54, 0.40, z0 + 2.55)
    limb(B, sh, el, 0.17, 0.15, 10)
    ellipsoid(B, el, 0.15, 0.15, 0.15, 8, 4)
    limb(B, el, hd, 0.15, 0.115, 10)
    limb(M, hd, hd + V(0.0, 0.0, -0.0), 0.12, 0.12, 6)
    ellipsoid(B, hd, 0.115, 0.12, 0.115, 8, 4)
    limb(M, hd + V(0.34, -0.03, 0.03), hd + V(-0.32, 0.06, -0.03), 0.06, 0.055, 8)
    # левая рука (−X): согнута, кисть на эфесе у пояса
    sh, el, hd = V(-0.66, 0.0, z0 + 3.72), V(-0.76, -0.06, z0 + 2.88), V(-0.40, 0.31, z0 + 2.74)
    limb(B, sh, el, 0.17, 0.15, 10)
    ellipsoid(B, el, 0.15, 0.15, 0.15, 8, 4)
    limb(B, el, hd, 0.15, 0.115, 10)
    ellipsoid(B, hd, 0.115, 0.12, 0.115, 8, 4)
    # сабля: рукоять в руке, ножны вдоль левого бока и позади
    limb(M, V(-0.40, 0.33, z0 + 2.95), V(-0.44, 0.31, z0 + 2.62), 0.035, 0.035, 6)
    limb(M, V(-0.52, 0.22, z0 + 2.62), V(-0.64, 0.10, z0 + 0.95), 0.036, 0.03, 6)
    slab(M, -0.36, -0.28, 0.27, 0.34, z0 + 2.97, z0 + 3.0)
    # пуговицы двумя рядами
    for i in range(7):
        zz = z0 + 1.55 + i * 0.30
        wd = 0.15 + 0.01 * i
        ry = 0.34 - 0.012 * min(i, 5) + 0.0
        for s in (-1, 1):
            ellipsoid(M, V(s * wd, ry - 0.03 + 0.04 * (i > 4), zz), 0.028, 0.014, 0.028, 4, 2)
    # ремень
    loft(M, [(0, 0, z0 + 2.58, 0.468, 0.288), (0, 0, z0 + 2.68, 0.472, 0.292)], 22, cap0=False, cap1=False)

def build():
    build_base()
    build_pedestal()
    build_figure()
    rot_all(FACING_DEG)

build()
finish('nahimov_monument', __file__, 25000)
