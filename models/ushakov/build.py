# Памятник-бюст адмиралу Ф. Ф. Ушакову (площадь Ушакова), Севастополь.
#
#   blender -b --python models/ushakov/build.py -- [glb]
#
# Бронзовый бюст на сужающемся гранитном постаменте с бронзовым картушем «Адмирал Ушаков 1744–1817»
# (якорь, лавровый венок) на ступенчатом гранитном основании. Размеры — по масштабу фото r1.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = -127.0, 1821.0
origin(X0, Z0)
set_rot(world_rot(0.4, -0.9))
COL['wall3'] = ((0.17, 0.21, 0.19), 0.5)
COL['metal'] = ((0.14, 0.17, 0.15), 0.5)
COL['wall2'] = ((0.62, 0.60, 0.57), 0.6)      # светло-серый гранит
COL['stone'] = ((0.50, 0.40, 0.38), 0.9)      # брусчатка
B = 'wall3'; G = 'wall2'
F0 = FR()

box('stone', F0, -3.0, 3.0, -3.0, 3.0, -0.3, 0.02)
frustum(G, F0, (-1.9, 1.9, -1.9, 1.9), (-1.55, 1.55, -1.55, 1.55), -0.2, 0.55)     # нижняя скошенная плита
box(G, F0, -1.2, 1.2, -1.0, 1.0, 0.55, 0.85)
frustum(G, F0, (-0.95, 0.95, -0.80, 0.80), (-0.82, 0.82, -0.70, 0.70), 0.85, 1.55)   # нижний блок
frustum(G, F0, (-0.78, 0.78, -0.68, 0.68), (-0.62, 0.62, -0.52, 0.52), 1.55, 3.15)   # сужающийся столб
box(G, F0, -0.7, 0.7, -0.6, 0.6, 3.15, 3.30)
box(G, F0, -0.62, 0.62, -0.52, 0.52, 3.30, 3.62)
blob(G, Vector((0.50, 0, 3.46)), 0.05, 0.06, 0.06, seg=8, rings=3)                    # розетка-кнопка
# картуш с якорем и надписью
Fc = FR(0, 0, -90)
dd = 0.62 - 0.0
x0 = 0.70
box('metal', F0, x0 - 0.05, x0 + 0.04, -0.28, 0.28, 2.10, 2.75)
box('metal', F0, x0 - 0.03, x0 + 0.07, -0.22, 0.22, 2.18, 2.58)
plate('metal', FR(0, 0, -90), -0.18, 0.18, x0 + 0.07, 2.25, 2.5, lines=2, seed=11, pr=0.01)
# бюст
z = 3.62; k = 1.4
rings = [(0.0, 0.46, 0.26), (0.14, 0.52, 0.27), (0.30, 0.50, 0.24), (0.40, 0.32, 0.18), (0.50, 0.14, 0.13), (0.58, 0.12, 0.12)]
rs = []
for dz, ry, rx in rings:
    rs.append(ring_pts(Vector((0.0, 0.0, z + dz * k)), Vector((1, 0, 0)), Vector((0, 1, 0)), rx * k, ry * k, 14))
loft(B, rs, True, True, True, True)
blob(B, Vector((0.04 * k, 0, z + 0.78 * k)), 0.17 * k, 0.14 * k, 0.22 * k, seg=10, rings=6)               # голова
blob(B, Vector((-0.04 * k, 0, z + 0.84 * k)), 0.17 * k, 0.16 * k, 0.17 * k, seg=8, rings=4, bot=0.3)      # парик
blob(B, Vector((0.19 * k, 0, z + 0.74 * k)), 0.04 * k, 0.035 * k, 0.06 * k, seg=6, rings=3)               # нос
for s_ in (-1, 1):                                                                                      # эполеты
    blob(B, Vector((0.0, s_ * 0.44 * k, z + 0.36 * k)), 0.14 * k, 0.07 * k, 0.03 * k, seg=8, rings=3)
tube(B, [P(0.15 * k, -0.14 * k, z + 0.40 * k), P(0.22 * k, 0.0, z + 0.14 * k), P(0.15 * k, 0.14 * k, z + 0.40 * k)], [0.03, 0.03, 0.03], 6)
done('ushakov', __file__, -127.0, 1821.0, 'Памятник-бюст адмиралу Ф. Ф. Ушакову')
