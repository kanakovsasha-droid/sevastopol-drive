# Памятник «Мужеству, стойкости и верности комсомольцев» (комсомольцам — защитникам Севастополя), Севастополь.
#
#   blender -b --python models/komsomolcam/build.py -- [glb]
#
# По фото Викисклада (refs/r3, r6): три бронзовые фигуры (стоящий боец с винтовкой со штыком в плащ-палатке,
# пригнувшийся с гранатами и автоматом и третий, залёгший сзади) на бронзовом камне; ступенчатый постамент из гранитных
# блоков с надписью «Мужеству, стойкости, верности комсомольцев».
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mon_kit import *

X0, Z0 = 150.4, 887.5
origin(X0, Z0)
set_rot(world_rot(-1.0, 0.05))
COL['wall3'] = ((0.30, 0.22, 0.15), 0.55)      # коричневая бронза
COL['metal'] = ((0.18, 0.15, 0.12), 0.5)
COL['wall2'] = ((0.50, 0.50, 0.46), 0.8)       # серый гранит
COL['stone'] = ((0.58, 0.55, 0.50), 0.9)
B = 'wall3'; G = 'wall2'
F0 = FR()

box('stone', F0, -3.4, 3.4, -3.4, 3.4, -0.3, 0.03)
box(G, F0, -2.9, 2.9, -2.9, 2.9, 0.0, 0.4)
box(G, F0, -2.5, 2.5, -2.5, 2.5, 0.4, 0.8)
frustum(G, F0, (-1.9, 1.9, -1.9, 1.9), (-1.75, 1.75, -1.75, 1.75), 0.8, 3.3)         # блок постамента
# швы кладки и надпись «МУЖЕСТВУ СТОЙКОСТИ ВЕРНОСТИ КОМСОМОЛЬЦЕВ»
for z in (1.6, 2.4):
    box('stone', F0, -1.85, 1.85, -1.85, 1.85, z, z + 0.03)
plate('metal', FR(0, 0, -90), -1.2, 1.2, 1.88, 1.9, 2.8, lines=4, seed=61, pr=0.02)
box(G, F0, -2.05, 2.05, -2.05, 2.05, 3.3, 3.5)
# бронзовая скала
for c, rx, ry, rz in (((0.0, 0.0, 3.8), 1.9, 1.9, 0.5), ((-0.4, 0.5, 4.3), 1.2, 1.1, 0.5), ((0.8, -0.6, 4.1), 0.9, 0.8, 0.45), ((-1.0, -1.0, 3.95), 0.7, 0.8, 0.4)):
    blob(B, Vector(c), rx, ry, rz, seg=8, rings=4)
zb = 4.1
# стоящий боец (винтовка со штыком, плащ-палатка)
fg = Fig(3.1, face=(1, 0, 0), bulk=1.2, seg=8)
person(B, fg, pel=(-0.35, 0.75, zb + 1.5), neck=(-0.3, 0.75, zb + 2.55), head=(-0.2, 0.75, zb + 2.88),
       shL=(-0.35, 1.2, zb + 2.4), shR=(-0.35, 0.3, zb + 2.4),
       haL=(0.1, 1.0, zb + 1.7), haR=(0.2, 0.45, zb + 1.8),
       hipL=(-0.35, 0.9, zb + 1.4), hipR=(-0.35, 0.6, zb + 1.4),
       anL=(-0.3, 0.95, zb + 0.15), anR=(0.1, 0.55, zb + 0.15),
       polesA=((0, 0.3, -1), (0, -0.2, -1)), polesL=((1, 0, 0.2), (1, 0, 0.2)), head_kind='helmet',
       torso_w=1.2, head_r=1.0, arm_r=1.15, leg_r=1.1)
skirt(B, [(Vector((-0.65, 0.75, zb + 2.4)), 0.25, 0.65, None), (Vector((-0.75, 0.8, zb + 1.3)), 0.3, 0.8, lambda t: 1 + 0.07 * math.sin(4 * t)),
          (Vector((-0.8, 0.8, zb + 0.2)), 0.3, 0.85, None)], seg=12)
tube(B, [Vector((0.25, 0.45, zb + 0.9)), Vector((0.05, 0.45, zb + 2.3)), Vector((-0.35, 0.45, zb + 3.8)), Vector((-0.5, 0.45, zb + 4.5))], [0.07, 0.06, 0.05, 0.01], 5)
# пригнувшийся боец с гранатами и автоматом
fg2 = Fig(2.7, face=(1, 0, 0), bulk=1.2, seg=8)
person(B, fg2, pel=(0.05, -0.25, zb + 1.2), neck=(0.7, -0.25, zb + 1.95), head=(0.95, -0.25, zb + 2.15),
       shL=(0.7, 0.2, zb + 1.85), shR=(0.7, -0.7, zb + 1.85),
       haL=(1.2, 0.05, zb + 1.0), haR=(1.4, -0.7, zb + 0.9),
       hipL=(0.05, -0.05, zb + 1.1), hipR=(0.05, -0.45, zb + 1.1),
       anL=(0.9, 0.0, zb + 0.15), anR=(-0.5, -0.5, zb + 0.15),
       polesA=((0, 0, -1), (0, 0, -1)), polesL=((1, 0, 0.8), (1, 0, 0.3)), head_kind='helmet',
       torso_w=1.2, head_r=1.0, arm_r=1.15, leg_r=1.1)
tube(B, [Vector((1.0, -0.8, zb + 0.9)), Vector((1.7, -0.7, zb + 0.8)), Vector((2.3, -0.65, zb + 0.75))], [0.07, 0.05, 0.04], 5)
# третий боец — припал сзади слева
fg3 = Fig(2.3, face=(1, 0, 0), bulk=1.2, seg=8)
person(B, fg3, pel=(-0.4, -1.4, zb + 0.9), neck=(0.05, -1.4, zb + 1.55), head=(0.25, -1.4, zb + 1.75),
       shL=(0.0, -1.0, zb + 1.5), shR=(0.0, -1.8, zb + 1.5),
       haL=(0.5, -1.1, zb + 0.9), haR=(0.5, -1.7, zb + 0.9),
       hipL=(-0.4, -1.25, zb + 0.85), hipR=(-0.4, -1.55, zb + 0.85),
       anL=(0.2, -1.2, zb + 0.12), anR=(-0.8, -1.6, zb + 0.12),
       polesA=((0, 0, -1), (0, 0, -1)), polesL=((1, 0, 0.8), (1, 0, 0.3)), head_kind='cap', torso_w=1.2, head_r=1.0)
done('komsomolcam', __file__, 150.4, 887.5, 'Памятник комсомольцам — защитникам Севастополя')
