# Вывески магазина «Купеческий» на сталинке ул. Льва Толстого, 2/16.
#
#   blender -b --python models/sign_kupecheskiy/build.py -- [glb]
#
# Сам дом рисует игра (серия «сталинка», арка-проезд — passage.js); здесь
# только то, что висит на его уличной (восточной) стене: над витриной первого
# этажа — объёмные жёлто-зелёные буквы «КУПЕЧЕСКИЙ» узорным шрифтом с тёмно-
# зелёной обводкой, слева от входа — табличка «КУПЕЧЕСКИЙ / МАРКЕТ», справа —
# синий короб «АВИАКАССА». Фото — карточка магазина на Яндекс Картах
# (refs/malls/kupech). Арку (левее, к югу) не трогаем: вывески кончаются за
# 2 м до её проёма. Контур OSM дома не снимаем — это не замена дома.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from mall_kit import *

# уличная стена w93168291 и точки OSM
WA, WB = (-752.4, 2179.1), (-767.3, 2239.1)
INSIDE = (-770.0, 2214.0)
SHOP = (-764.1, 2214.0)            # «Купеческий»
GATE = (-762.8, 2221.0, 3.6)       # середина арки и её ширина (data/houses.json)
F0, L0 = frame_lr(WA, WB, INSIDE)  # u растёт к северу — вправо для того, кто смотрит с улицы
o = F0.o + F0.u * ((W(*SHOP) - F0.o).dot(F0.u))
origin(o.x, -o.y)                  # начало — на стене напротив магазина
X0, Z0 = o.x, -o.y
F, L = frame_lr(WA, WB, INSIDE)
us = (W(*SHOP) - F.o).dot(F.u)
ug = (W(GATE[0], GATE[1]) - F.o).dot(F.u)

# Отметка первого этажа в игре — самая высокая точка земли у стен дома
# (worldgen.js, yFloor = gmax); модель же ставится на землю в своём начале.
# Замер в игре: gmax 76.19, земля у начала 73.11 — этаж на 3.08 м выше.
FLOOR = 76.19 - 73.11
# этаж — как в facades.js (stalinka): fh0 = 3.6 м, число этажей округляется
import math as _m
NF = max(1, _m.floor(10.7 / 3.6 + 0.35))
FH = 10.7 / NF
ZS = FLOOR + FH + 0.13             # низ букв — на тяге над первым этажом, под окнами второго

mat('yellow', (0.93, 0.86, 0.12), 0.45)
mat('dkgreen', (0.07, 0.30, 0.12), 0.5)
mat('olive', (0.36, 0.33, 0.20), 0.6)
mat('white', (0.96, 0.96, 0.94), 0.5)
mat('blue', (0.10, 0.20, 0.55), 0.5)
lod_keep('blue')               # вдали — только короб, буквы видны вблизи

d = 0.12
# «КУПЕЧЕСКИЙ»: жёлтые буквы и тёмно-зелёная обводка за ними
text('dkgreen', F, 'КУПЕЧЕСКИЙ', us, ZS - 0.05, 0.62, d, depth=0.06, fnt='Georgia Bold.ttf', width=7.9, res=1)
text('yellow', F, 'КУПЕЧЕСКИЙ', us, ZS, 0.52, d + 0.06, depth=0.08, fnt='Georgia Bold.ttf', width=7.6, res=1)
# табличка слева от входа (к арке): «КУПЕЧЕСКИЙ / МАРКЕТ»
ul = max(us - 4.2, ug + GATE[2] / 2 + 2.0 + 0.9)
board(F, ul - 0.9, ul + 0.9, FLOOR + 2.05, FLOOR + 2.85, d, 'olive', depth=0.08)
text('white', F, 'КУПЕЧЕСКИЙ', ul, FLOOR + 2.5, 0.2, d + 0.08, depth=0.03, width=1.55)
text('white', F, 'МАРКЕТ', ul, FLOOR + 2.18, 0.14, d + 0.08, depth=0.03, width=0.75)
# справа — «АВИАКАССА»
ur = us + 4.6
board(F, ur - 1.1, ur + 1.1, FLOOR + 2.15, FLOOR + 2.75, d, 'blue', depth=0.08)
text('white', F, 'АВИАКАССА', ur, FLOOR + 2.32, 0.26, d + 0.08, depth=0.03, width=1.9)

print('НАЧАЛО', round(X0, 2), round(Z0, 2), 'арка u', round(ug - us, 2))
finish('sign_kupecheskiy', __file__)
